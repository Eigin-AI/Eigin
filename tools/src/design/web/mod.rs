const GENERATED_HEADER: &str =
    "// Generated by eigin-tools — edit design/tokens.json, not this file.\n";

pub fn generate(repo_root: &str, tokens: &Value, fonts: Option<&InstalledFonts>) -> Result<()> {
    let web_dir = Path::new(repo_root).join("design/web");
    if !web_dir.exists() {
        println!("Skipping the web target: design/web does not exist.");
        return Ok(());
    }
    let out_dir = web_dir.join("src/lib/generated");
    fs::create_dir_all(&out_dir).with_context(|| format!("creating {}", out_dir.display()))?;

    fs::write(out_dir.join("tokens.css"), css::render(tokens)?)?;

    let typography_css = typography::render(tokens, fonts)?;
    fs::write(out_dir.join("typography.css"), typography_css)?;

    fonts::generate(repo_root, tokens, fonts, &out_dir)?;

    fs::write(out_dir.join("tokens.ts"), render_tokens_ts(tokens)?)?;
    fs::write(
        out_dir.join("icons.ts"),
        icons::render(repo_root, GENERATED_HEADER)?,
    )?;

    Ok(())
}

/// Typed TS accessors for token names that components and the gallery need
/// as values, not just as CSS variables.
fn render_tokens_ts(tokens: &Value) -> Result<String> {
    let names: Vec<String> = TYPOGRAPHY_FIELDS
        .iter()
        .map(|s| format!("\"{s}\""))
        .collect();
    let breakpoints: Vec<String> = GRID_BREAKPOINTS
        .iter()
        .map(|(name, _, _)| format!("\"{name}\""))
        .collect();

    let mut color_entries = String::new();
    let tree = self::tokens::parse_color_tree(tokens)?;
    write_color_entries(&tree, &mut Vec::new(), &mut color_entries);

    let typography_entries = render_typography_entries(tokens)?;
    let scale_entries = render_scale_entries(tokens)?;

    use std::fmt::Write as _;
    let mut easing_entries = String::new();
    for entry in crate::design::tokens::parse_motion_easing(tokens)? {
        let [a, b, c, d] = entry.points;
        let doc = match &entry.description {
            Some(text) => format!(", description: {}", serde_json::to_string(text)?),
            None => String::new(),
        };
        let _ = writeln!(
            easing_entries,
            "  {{ name: \"{}\", curve: \"cubic-bezier({}, {}, {}, {})\"{doc} }},",
            entry.name,
            fmt_num(a),
            fmt_num(b),
            fmt_num(c),
            fmt_num(d)
        );
    }

    Ok(format!(
        "{GENERATED_HEADER}\nexport type TypographyName =\n  | {}\n\nexport const typographyNames = [\n  {},\n] as const;\n\nexport interface TypographyStyle {{\n  name: TypographyName;\n  /** Token family: display (sans), ui (serif), mono. */\n  family: \"display\" | \"ui\" | \"mono\";\n  fontWeight: number;\n  fontSize: number;\n  lineHeight: number;\n  letterSpacing: number;\n  textCase?: \"uppercase\";\n}}\n\nexport const typographyStyles: readonly TypographyStyle[] = [\n{typography_entries}];\n\nexport type GridBreakpointName = {};\n\nexport interface ColorToken {{\n  /** Dotted token path, e.g. `surface.standard.base`. */\n  name: string;\n  light: string;\n  dark: string;\n}}\n\nexport const colorTokens: readonly ColorToken[] = [\n{color_entries}];\n\nexport interface ScaleToken {{\n  /** Dotted token path, e.g. `button.height.large`. */\n  name: string;\n  /** Value in px, or a unitless ratio/count. */\n  value: number;\n  unit: \"px\" | \"ms\" | \"\";\n  description?: string;\n}}\n\nexport interface ScaleGroup {{\n  /** Token group, e.g. `spacing`. */\n  name: string;\n  tokens: readonly ScaleToken[];\n}}\n\nexport const scaleGroups: readonly ScaleGroup[] = [\n{scale_entries}];\n\nexport interface EasingToken {{\n  /** Curve name, matching the iOS animation presets. */\n  name: string;\n  /** CSS timing function, also available as --motion-easing-<name>. */\n  curve: string;\n  description?: string;\n}}\n\nexport const motionEasings: readonly EasingToken[] = [\n{easing_entries}];\n",
        names.join("\n  | "),
        names.join(",\n  "),
        breakpoints.join(" | ")
    ))
}

/// Dimension scales the gallery documents: spacing, radius, stroke weight,
/// component sizing and the grid. Values are px unless the token is a
/// unitless ratio or column count.
fn render_scale_entries(tokens: &Value) -> Result<String> {
    use std::fmt::Write;

    fn push_group(
        out: &mut String,
        name: &str,
        rows: &[(String, f64, &'static str, Option<String>)],
    ) {
        let _ = writeln!(out, "  {{");
        let _ = writeln!(out, "    name: \"{name}\",");
        let _ = writeln!(out, "    tokens: [");
        for (token, value, unit, description) in rows {
            let doc = match description {
                Some(text) => format!(", description: {}", serde_json::to_string(text).unwrap()),
                None => String::new(),
            };
            let _ = writeln!(
                out,
                "      {{ name: \"{token}\", value: {}, unit: \"{unit}\"{doc} }},",
                fmt_num(*value)
            );
        }
        let _ = writeln!(out, "    ],");
        let _ = writeln!(out, "  }},");
    }

    let mut out = String::new();

    let motion = crate::design::tokens::parse_motion(tokens)?;
    let rows: Vec<_> = motion
        .iter()
        .map(|e| (e.name.clone(), e.ms, "ms", e.description.clone()))
        .collect();
    push_group(&mut out, "motion", &rows);

    let spacing = parse_spacing(tokens)?;
    let rows: Vec<_> = spacing
        .entries
        .iter()
        .map(|e| (e.name.clone(), e.pts, "px", e.description.clone()))
        .collect();
    push_group(&mut out, "spacing", &rows);

    let radius_group = tokens
        .get("radius")
        .context("tokens.json: missing 'radius' group")?;
    let mut rows = Vec::new();
    for (name, token) in radius_group
        .as_object()
        .context("radius group is not an object")?
    {
        if name.starts_with('$') {
            continue;
        }
        let raw = token
            .get("$value")
            .and_then(Value::as_str)
            .with_context(|| format!("radius.{name}: missing $value"))?;
        // `full` is the unbounded pill radius, matching the Swift generator.
        let value = if name == "full" {
            9999.0
        } else {
            parse_dimension(raw).with_context(|| format!("radius.{name}: invalid '{raw}'"))?
        };
        rows.push((name.clone(), value, "px", None));
    }
    push_group(&mut out, "radius", &rows);

    let stroke = parse_stroke_weight(tokens)?;
    let rows: Vec<_> = stroke
        .entries
        .iter()
        .map(|e| (e.name.clone(), e.pts, "px", e.description.clone()))
        .collect();
    push_group(&mut out, "strokeWeight", &rows);

    fn walk(
        entries: &[SizingEntry],
        path: &mut Vec<String>,
        rows: &mut Vec<(String, f64, &'static str, Option<String>)>,
    ) {
        for entry in entries {
            match entry {
                SizingEntry::Leaf {
                    name,
                    pts,
                    unitless,
                } => {
                    path.push(name.clone());
                    rows.push((
                        path.join("."),
                        *pts,
                        if *unitless { "" } else { "px" },
                        None,
                    ));
                    path.pop();
                }
                SizingEntry::Group { name, children } => {
                    path.push(name.clone());
                    walk(children, path, rows);
                    path.pop();
                }
            }
        }
    }
    let sizing = parse_sizing(tokens)?;
    let mut rows = Vec::new();
    walk(&sizing.entries, &mut Vec::new(), &mut rows);
    push_group(&mut out, "sizing", &rows);

    let grid = parse_grid(tokens)?;
    let mut rows = Vec::new();
    for bp in &grid.breakpoints {
        rows.push((
            format!("{}.columns", bp.name),
            bp.columns as f64,
            "",
            Some(bp.doc.clone()),
        ));
        rows.push((format!("{}.outer", bp.name), bp.outer, "px", None));
        rows.push((format!("{}.inner", bp.name), bp.inner, "px", None));
        rows.push((format!("{}.gutter", bp.name), bp.gutter, "px", None));
    }
    push_group(&mut out, "grid", &rows);

    Ok(out)
}

/// One record per typography style, in canonical token order.
fn render_typography_entries(tokens: &Value) -> Result<String> {
    let group = tokens
        .get("typography")
        .context("tokens.json: missing 'typography' group")?;
    let mut out = String::new();
    use std::fmt::Write;
    for name in TYPOGRAPHY_FIELDS {
        let value = group
            .get(*name)
            .and_then(|t| t.get("$value"))
            .with_context(|| format!("typography.{name}: missing $value"))?;
        let family = value
            .get("fontFamily")
            .and_then(Value::as_str)
            .with_context(|| format!("typography.{name}: missing fontFamily"))?;
        let weight = css_font_weight(
            value
                .get("fontWeight")
                .and_then(Value::as_str)
                .with_context(|| format!("typography.{name}: missing fontWeight"))?,
        )?;
        let size = value
            .get("fontSize")
            .and_then(Value::as_f64)
            .with_context(|| format!("typography.{name}: missing fontSize"))?;
        let line_height = value
            .get("lineHeight")
            .and_then(Value::as_f64)
            .with_context(|| format!("typography.{name}: missing lineHeight"))?;
        let spacing = resolve_letter_spacing(tokens, value, name)?;
        let text_case = value
            .get("textCase")
            .and_then(Value::as_str)
            .map(|c| format!("    textCase: \"{c}\",\n"))
            .unwrap_or_default();
        let _ = writeln!(
            out,
            "  {{ name: \"{name}\", family: \"{family}\", fontWeight: {weight}, fontSize: {}, lineHeight: {}, letterSpacing: {},\n{text_case}  }},",
            fmt_num(size),
            fmt_num(line_height),
            fmt_num(spacing)
        );
    }
    Ok(out)
}

fn write_color_entries(node: &tokens::ColorTree, path: &mut Vec<String>, out: &mut String) {
    use std::fmt::Write;
    path.push(node.name.clone());
    if let Some(leaf) = &node.leaf {
        let _ = writeln!(
            out,
            "  {{ name: \"{}\", light: \"{}\", dark: \"{}\" }},",
            path[1..].join("."),
            leaf.light_hex,
            leaf.dark_hex
        );
    }
    for child in &node.children {
        write_color_entries(child, path, out);
    }
    path.pop();
}

/// Formats an f64 the way design tokens want it: whole numbers without a
/// decimal part, otherwise as-is.
pub(crate) fn fmt_num(value: f64) -> String {
    if value.fract() == 0.0 {
        format!("{}", value as i64)
    } else {
        format!("{value}")
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    #[test]
    fn typography_records_carry_family_and_metrics() {
        // Every canonical style must be present; give them generic values.
        let styles: serde_json::Map<String, Value> = TYPOGRAPHY_FIELDS
            .iter()
            .map(|name| {
                let family = if name.starts_with("button") {
                    "display"
                } else {
                    "ui"
                };
                (
                    name.to_string(),
                    json!({ "$type": "typography", "$value": {
                        "fontFamily": family, "fontWeight": "regular",
                        "fontSize": 17, "lineHeight": 23.8, "letterSpacing": "standard" } }),
                )
            })
            .collect();
        let mut typography = styles;
        typography.insert(
            "button".into(),
            json!({ "$type": "typography", "$value": {
                "fontFamily": "display", "fontWeight": "bold",
                "fontSize": 16, "lineHeight": 16, "letterSpacing": "s",
                "textCase": "uppercase" } }),
        );
        let spacing: serde_json::Map<String, Value> = [
            2, 4, 8, 12, 16, 20, 24, 28, 32, 40, 48, 56, 64, 72, 80, 88, 128,
        ]
        .into_iter()
        .map(|n| (format!("n{n}"), json!({ "$value": format!("{n}px") })))
        .collect();
        let tokens = json!({
            "color": {},
            "letterSpacing": { "standard": { "$value": "0px" }, "s": { "$value": "0.5px" } },
            "spacing": spacing,
            "radius": { "card": { "$value": "24px" }, "full": { "$value": "9999px" } },
            "strokeWeight": { "standard": { "$value": "3px" } },
            "sizing": {
                "gap": { "$type": "dimension", "$value": "{spacing.n8}" },
                "ratio": { "$type": "number", "$value": 1.5 }
            },
            "grid": {
                "mobile": { "columns": { "$type": "number", "$value": 2 },
                    "outer": { "$type": "dimension", "$value": "8px" },
                    "inner": { "$type": "dimension", "$value": "32px" },
                    "gutter": { "$type": "dimension", "$value": "16px" } },
                "tablet": { "columns": { "$type": "number", "$value": 4 },
                    "outer": { "$type": "dimension", "$value": "16px" },
                    "inner": { "$type": "dimension", "$value": "40px" },
                    "gutter": { "$type": "dimension", "$value": "24px" } },
                "desktop": { "columns": { "$type": "number", "$value": 4 },
                    "outer": { "$type": "dimension", "$value": "24px" },
                    "inner": { "$type": "dimension", "$value": "56px" },
                    "gutter": { "$type": "dimension", "$value": "24px" } }
            },
            "motion": {
                "fast": { "$type": "duration", "$value": "150ms" },
                "normal": { "$type": "duration", "$value": "250ms" },
                "slow": { "$type": "duration", "$value": "400ms" },
                "easing": {
                    "smooth": { "$type": "cubicBezier", "$value": [0.42, 0, 0.58, 1] },
                    "snap": { "$type": "cubicBezier", "$value": [0.34, 1.26, 0.64, 1] },
                    "gentle": { "$type": "cubicBezier", "$value": [0.32, 1.12, 0.56, 1] }
                }
            },
            "typography": typography,
        });
        let ts = render_tokens_ts(&tokens).unwrap();
        // Scales the spacing page documents, with ratios kept unitless.
        assert!(ts.contains("name: \"spacing\","));
        assert!(ts.contains("{ name: \"n8\", value: 8, unit: \"px\" }"));
        assert!(ts.contains("{ name: \"ratio\", value: 1.5, unit: \"\" }"));
        assert!(ts.contains("{ name: \"fast\", value: 150, unit: \"ms\""));
        assert!(ts.contains("{ name: \"full\", value: 9999, unit: \"px\" }"));
        assert!(ts.contains("name: \"body\", family: \"ui\", fontWeight: 400, fontSize: 17, lineHeight: 23.8, letterSpacing: 0,"));
        assert!(
            ts.contains("name: \"button\", family: \"display\", fontWeight: 700, fontSize: 16")
        );
        assert!(ts.contains("textCase: \"uppercase\","));
    }
}
