//! tokens.css: the token tree as CSS custom properties.
//!
//! Light values live on `:root` (and an explicit light block), dark overrides
//! on `[data-color-scheme="dark"]` — only leaves whose dark value differs.

use anyhow::{Context, Result};
use serde_json::Value;
use std::fmt::Write;

use crate::design::tokens::{
    ColorTree, SizingEntry, parse_color_tree, parse_dimension, parse_grid, parse_motion,
    parse_motion_easing, parse_sizing, parse_spacing, parse_stroke_weight,
};

use super::fmt_num;

pub fn render(tokens: &Value) -> Result<String> {
    let mut light = String::new();
    let mut dark = String::new();

    let tree = parse_color_tree(tokens)?;
    write_colors(&tree, &mut Vec::new(), &mut light, &mut dark);

    for (name, pts) in &parse_spacing(tokens)?
        .entries
        .into_iter()
        .map(|e| (e.name, e.pts))
        .collect::<Vec<_>>()
    {
        let _ = writeln!(light, "--spacing-{name}: {}px;", fmt_num(*pts));
    }

    write_radius(&mut light, tokens)?;
    for (name, pts) in &parse_stroke_weight(tokens)?
        .entries
        .into_iter()
        .map(|e| (e.name, e.pts))
        .collect::<Vec<_>>()
    {
        let _ = writeln!(light, "--stroke-weight-{name}: {}px;", fmt_num(*pts));
    }

    for entry in parse_motion(tokens)? {
        let _ = writeln!(light, "--motion-{}: {}ms;", entry.name, fmt_num(entry.ms));
    }
    for entry in parse_motion_easing(tokens)? {
        let [a, b, c, d] = entry.points;
        let _ = writeln!(
            light,
            "--motion-easing-{}: cubic-bezier({}, {}, {}, {});",
            entry.name,
            fmt_num(a),
            fmt_num(b),
            fmt_num(c),
            fmt_num(d)
        );
    }

    write_sizing(&mut light, tokens)?;
    write_grid(&mut light, tokens)?;
    write_letter_spacing(&mut light, tokens)?;
    write_font_families(&mut light, tokens)?;

    let dark_block = if dark.is_empty() {
        String::new()
    } else {
        format!("\n[data-color-scheme=\"dark\"] {{\n{dark}}}\n")
    };

    // Motion collapses to zero when the reader asks for reduced motion.
    let reduced_motion = {
        let mut block = String::from("\n@media (prefers-reduced-motion: reduce) {\n  :root {\n");
        for entry in parse_motion(tokens)? {
            let _ = writeln!(block, "    --motion-{}: 0ms;", entry.name);
        }
        block.push_str("  }\n}\n");
        block
    };

    Ok(format!(
        "/* Generated by eigin-tools — edit design/tokens.json, not this file. */\n\n:root,\n[data-color-scheme=\"light\"] {{\n{light}}}\n{dark_block}{reduced_motion}"
    ))
}

// --- colors ---

fn write_colors(node: &ColorTree, path: &mut Vec<String>, light: &mut String, dark: &mut String) {
    path.push(node.name.clone());
    if let Some(leaf) = &node.leaf {
        let var = format!("--{}", path.join("-"));
        let _ = writeln!(light, "{var}: {};", leaf.light_hex);
        if leaf.dark_hex != leaf.light_hex {
            let _ = writeln!(dark, "{var}: {};", leaf.dark_hex);
        }
    }
    for child in &node.children {
        write_colors(child, path, light, dark);
    }
    path.pop();
}

// --- dimensions ---

fn write_radius(out: &mut String, tokens: &Value) -> Result<()> {
    let group = tokens
        .get("radius")
        .context("tokens.json: missing 'radius' group")?;
    for (name, token) in group.as_object().context("radius group is not an object")? {
        let raw = token
            .get("$value")
            .and_then(Value::as_str)
            .with_context(|| format!("radius.{name}: missing string $value"))?;
        // Matches the Swift generator's treatment of `full` as an unbounded radius.
        let value = if name == "full" {
            9999.0
        } else {
            parse_dimension(raw).with_context(|| format!("radius.{name}: invalid '{raw}'"))?
        };
        let _ = writeln!(out, "--radius-{name}: {}px;", fmt_num(value));
    }
    Ok(())
}

fn write_sizing(out: &mut String, tokens: &Value) -> Result<()> {
    fn walk(entries: &[SizingEntry], path: &mut Vec<String>, out: &mut String) -> Result<()> {
        for entry in entries {
            match entry {
                SizingEntry::Leaf {
                    name,
                    pts,
                    unitless,
                } => {
                    path.push(name.clone());
                    let unit = if *unitless { "" } else { "px" };
                    let _ = writeln!(out, "--sizing-{}: {}{unit};", path.join("-"), fmt_num(*pts));
                    path.pop();
                }
                SizingEntry::Group { name, children } => {
                    path.push(name.clone());
                    walk(children, path, out)?;
                    path.pop();
                }
            }
        }
        Ok(())
    }
    let scale = parse_sizing(tokens)?;
    walk(&scale.entries, &mut Vec::new(), out)
}

fn write_grid(out: &mut String, tokens: &Value) -> Result<()> {
    for bp in parse_grid(tokens)?.breakpoints {
        let _ = writeln!(out, "--grid-{}-columns: {};", bp.name, bp.columns);
        for (field, value) in [
            ("outer", bp.outer),
            ("inner", bp.inner),
            ("gutter", bp.gutter),
        ] {
            let _ = writeln!(out, "--grid-{}-{}: {}px;", bp.name, field, fmt_num(value));
        }
    }
    Ok(())
}

fn write_letter_spacing(out: &mut String, tokens: &Value) -> Result<()> {
    let group = tokens
        .get("letterSpacing")
        .context("tokens.json: missing 'letterSpacing' group")?;
    for (name, token) in group
        .as_object()
        .context("letterSpacing group is not an object")?
    {
        let raw = token
            .get("$value")
            .and_then(Value::as_str)
            .with_context(|| format!("letterSpacing.{name}: missing string $value"))?;
        let value = parse_dimension(raw)
            .with_context(|| format!("letterSpacing.{name}: invalid '{raw}'"))?;
        let _ = writeln!(out, "--letter-spacing-{name}: {}px;", fmt_num(value));
    }
    Ok(())
}

// --- fonts ---

/// Stack suffixes per family role, used when font files are absent.
const FALLBACK_STACKS: &[(&str, &str)] = &[
    ("display", "\"system-ui\", sans-serif"),
    ("ui", "Georgia, serif"),
    ("mono", "\"ui-monospace\", monospace"),
];

fn write_font_families(out: &mut String, tokens: &Value) -> Result<()> {
    let group = tokens
        .get("fontFamily")
        .context("tokens.json: missing 'fontFamily' group")?;
    for family in group
        .as_object()
        .context("fontFamily group is not an object")?
        .keys()
    {
        let fallback = FALLBACK_STACKS
            .iter()
            .find(|(name, _)| name == family)
            .map(|(_, stack)| *stack)
            .unwrap_or("sans-serif");
        // Face name = PostScript prefix (what fonts.css declares); the var
        // falls through the stack when fonts aren't installed.
        let postscript = family_postscript(group, family);
        let face = postscript.split('-').next().unwrap_or(postscript);
        let _ = writeln!(out, "--font-{family}: \"{face}\", {fallback};");
    }
    Ok(())
}

/// The first PostScript name declared for a family, in weight order.
fn family_postscript<'a>(group: &'a Value, family: &'a str) -> &'a str {
    const ORDER: &[&str] = &["regular", "bold", "light", "medium", "demibold"];
    let Some(map) = group.get(family).and_then(Value::as_object) else {
        return family;
    };
    ORDER
        .iter()
        .find_map(|w| map.get(*w).and_then(Value::as_str))
        .unwrap_or(family)
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    #[test]
    fn emits_light_and_dark_diff() {
        // parse_spacing requires the full canonical scale.
        let spacing: serde_json::Map<String, Value> = crate::design::tokens::SPACING_FIELDS
            .iter()
            .map(|name| {
                let n: f64 = name.trim_start_matches('n').parse().unwrap();
                (name.to_string(), json!({ "$value": format!("{n}px") }))
            })
            .collect();
        let tokens = json!({
            "palette": { "n": { "1": { "$type": "color", "$value": "#FFFFFF",
                "$modes": { "dark": "#000000" } } } },
            "color": { "surface": {
                "base": { "$type": "color", "$value": "{palette.n.1}" },
                "text": { "$type": "color", "$value": "#111111" }
            } },
            "spacing": spacing,
            "radius": { "card": { "$value": "24px" }, "full": { "$value": "9999px" } },
            "strokeWeight": { "standard": { "$value": "3px" } },
            "grid": {
                "mobile": { "columns": { "$type": "number", "$value": 2 },
                    "outer": { "$type": "dimension", "$value": "8px" },
                    "inner": { "$type": "dimension", "$value": "32px" },
                    "gutter": { "$type": "dimension", "$value": "16px" } },
                "tablet": { "columns": { "$type": "number", "$value": 4 },
                    "outer": { "$type": "dimension", "$value": "16px" },
                    "inner": { "$type": "dimension", "$value": "40px" },
                    "gutter": { "$type": "dimension", "$value": "24px" } },
                "desktop": { "columns": { "$type": "number", "$value": 4 },
                    "outer": { "$type": "dimension", "$value": "24px" },
                    "inner": { "$type": "dimension", "$value": "56px" },
                    "gutter": { "$type": "dimension", "$value": "24px" } }
            },
            "sizing": {
                "gap": { "$type": "dimension", "$value": "{spacing.n8}" },
                "ratio": { "$type": "number", "$value": 1.5 }
            },
            "letterSpacing": { "s": { "$value": "0.5px" } },
            "motion": {
                "fast": { "$type": "duration", "$value": "150ms" },
                "normal": { "$type": "duration", "$value": "250ms" },
                "slow": { "$type": "duration", "$value": "400ms" },
                "easing": {
                    "smooth": { "$type": "cubicBezier", "$value": [0.42, 0, 0.58, 1] },
                    "snap": { "$type": "cubicBezier", "$value": [0.34, 1.26, 0.64, 1] },
                    "gentle": { "$type": "cubicBezier", "$value": [0.32, 1.12, 0.56, 1] }
                }
            },
            "fontFamily": { "ui": { "regular": "Some-Regular" } }
        });
        let css = render(&tokens).unwrap();
        assert!(css.contains("--color-surface-base: #FFFFFF;"));
        assert!(css.contains("--color-surface-text: #111111;"));
        assert!(css.contains("--spacing-n8: 8px;"));
        assert!(css.contains("--radius-card: 24px;"));
        assert!(css.contains("--radius-full: 9999px;"));
        assert!(css.contains("--grid-mobile-inner: 32px;"));
        assert!(css.contains("--sizing-gap: 8px;"));
        // `number` tokens are ratios/counts and must stay unitless.
        assert!(css.contains("--sizing-ratio: 1.5;"));
        // Motion tiers, plus the reduced-motion override.
        assert!(css.contains("--motion-fast: 150ms;"));
        assert!(css.contains("--motion-slow: 400ms;"));
        assert!(css.contains("@media (prefers-reduced-motion: reduce)"));
        assert!(css.contains("--motion-normal: 0ms;"));
        assert!(css.contains("--motion-easing-smooth: cubic-bezier(0.42, 0, 0.58, 1);"));
        assert!(css.contains("--motion-easing-snap: cubic-bezier(0.34, 1.26, 0.64, 1);"));
        assert!(css.contains("--letter-spacing-s: 0.5px;"));
        assert!(css.contains("--font-ui: \"Some\", Georgia, serif;"));
        // Dark block, only for leaves that differ.
        let dark = css.split("[data-color-scheme=\"dark\"]").nth(1).unwrap();
        assert!(dark.contains("--color-surface-base: #000000;"));
        assert!(!dark.contains("surface-text"));
    }

    #[test]
    fn numbers_render_without_trailing_zeros() {
        assert_eq!(fmt_num(24.0), "24");
        assert_eq!(fmt_num(23.8), "23.8");
    }
}
