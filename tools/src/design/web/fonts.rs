//! Web fonts: copy font files next to the generated CSS and emit `@font-face`
//! rules keyed by the token family map. Skipped when no fonts are present
//! (the proprietary-font path) — the CSS fallback stacks take over.

use anyhow::{Context, Result};
use serde_json::Value;
use std::fs;
use std::path::{Path, PathBuf};
use walkdir::WalkDir;

use crate::design::ios::fonts::InstalledFonts;

struct FontFile {
    path: PathBuf,
    stem: String,
    extension: String,
}

pub fn generate(
    repo_root: &str,
    tokens: &Value,
    fonts: Option<&InstalledFonts>,
    out_dir: &Path,
) -> Result<()> {
    let Some(installed) = fonts else {
        return Ok(());
    };
    let source_dir = PathBuf::from(repo_root).join("design/assets/fonts");
    let files = font_files(&source_dir)?;

    let fonts_dir = out_dir.join("fonts");
    if fonts_dir.exists() {
        fs::remove_dir_all(&fonts_dir)
            .with_context(|| format!("clearing {}", fonts_dir.display()))?;
    }
    fs::create_dir_all(&fonts_dir).with_context(|| format!("creating {}", fonts_dir.display()))?;

    let mut css = String::from(
        "/* Generated by eigin-tools — fonts are machine-local; add them to design/assets/fonts/. */\n",
    );

    for family in installed.family_names() {
        // Face = PostScript prefix ("NorthEastCN-…" → "NorthEastCN").
        let face = family_postscript(installed, family)
            .split('-')
            .next()
            .unwrap_or(family)
            .to_string();
        let features = installed.family_features(family);
        let feature_line = if features.is_empty() {
            String::new()
        } else {
            let settings = features
                .iter()
                .map(|f| format!("\"{}\" {}", f.tag, f.value))
                .collect::<Vec<_>>()
                .join(", ");
            format!("  font-feature-settings: {settings};\n")
        };

        for weight in family_weights(tokens, family) {
            let Some(ps_name) = installed.postscript_name(family, &weight) else {
                continue;
            };
            let Some(file) = pick_file(&files, ps_name) else {
                continue;
            };
            let file_name = file
                .path
                .file_name()
                .unwrap()
                .to_string_lossy()
                .into_owned();
            let format_name = match file.extension.as_str() {
                "otf" => "opentype",
                "ttf" => "truetype",
                other => anyhow::bail!("unexpected font extension: {other}"),
            };
            fs::copy(&file.path, fonts_dir.join(&file_name))
                .with_context(|| format!("copying font {}", file.path.display()))?;
            let number = crate::design::web::typography::css_font_weight(&weight)?;
            css.push_str(&format!(
                "@font-face {{\n  font-family: \"{face}\";\n  src: url(\"./fonts/{file_name}\") format(\"{format_name}\");\n  font-weight: {number};\n  font-style: normal;\n{feature_line}}}\n"
            ));
        }
    }

    fs::write(out_dir.join("fonts.css"), css).context("writing fonts.css")?;
    Ok(())
}

fn family_postscript<'a>(installed: &'a InstalledFonts, family: &'a str) -> &'a str {
    ["regular", "bold", "light"]
        .iter()
        .find_map(|w| installed.postscript_name(family, w))
        .unwrap_or(family)
}

/// Weights declared for a family in tokens.json, light → heavy.
fn family_weights(tokens: &Value, family: &str) -> Vec<String> {
    let Some(map) = tokens
        .get("fontFamily")
        .and_then(|g| g.get(family))
        .and_then(Value::as_object)
    else {
        return Vec::new();
    };
    const ORDER: &[&str] = &[
        "extralight",
        "light",
        "regular",
        "medium",
        "demibold",
        "bold",
        "extrabold",
    ];
    ORDER
        .iter()
        .filter(|w| map.get(**w).and_then(Value::as_str).is_some())
        .map(|w| w.to_string())
        .collect()
}

/// Finds the file backing a PostScript name: exact stem first, then a stem
/// prefixed by the name (the " copy" duplicates in the font folder).
fn pick_file<'a>(files: &'a [FontFile], postscript: &str) -> Option<&'a FontFile> {
    files.iter().find(|f| f.stem == postscript).or_else(|| {
        files
            .iter()
            .find(|f| f.stem.starts_with(postscript) && !f.stem.contains("Italic"))
    })
}

fn font_files(source_dir: &Path) -> Result<Vec<FontFile>> {
    let mut files = Vec::new();
    for entry in WalkDir::new(source_dir).into_iter().filter_map(|e| e.ok()) {
        let path = entry.into_path();
        let extension = path
            .extension()
            .and_then(|e| e.to_str())
            .unwrap_or_default()
            .to_lowercase();
        if path.is_file() && matches!(extension.as_str(), "otf" | "ttf") {
            let stem = path
                .file_stem()
                .and_then(|s| s.to_str())
                .context("non-utf8 font filename")?
                .to_string();
            files.push(FontFile {
                path,
                stem,
                extension,
            });
        }
    }
    files.sort_by(|a, b| a.stem.cmp(&b.stem));
    Ok(files)
}
