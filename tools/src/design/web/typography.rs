//! typography.css: one class per typography style, built from CSS variables.

use anyhow::{Context, Result};
use serde_json::Value;
use std::fmt::Write;

use crate::design::ios::fonts::InstalledFonts;
use crate::design::tokens::{TYPOGRAPHY_FIELDS, resolve_letter_spacing};

use super::fmt_num;

pub fn render(tokens: &Value, fonts: Option<&InstalledFonts>) -> Result<String> {
    let group = tokens
        .get("typography")
        .context("tokens.json: missing 'typography' group")?;

    let mut out =
        String::from("/* Generated by eigin-tools — edit design/tokens.json, not this file. */\n");
    // Text is measured cap-height to baseline, the way Figma measures it, so
    // padding and gaps land where the design says. Browsers without text-box
    // support fall back to full line boxes.
    let selectors = TYPOGRAPHY_FIELDS
        .iter()
        .map(|name| format!(".t-{name}"))
        .collect::<Vec<_>>()
        .join(",\n");
    let _ = write!(
        out,
        "\n{selectors} {{\n  text-box: trim-both cap alphabetic;\n}}\n\n"
    );

    // Optical inset per style: the space a line box carries above the cap and below
    // the baseline, (lineHeight − capHeight) / 2. Components add it where a hard edge
    // has to read even against the prose's untrimmed line boxes, the way iOS's
    // `opticalInset` does. Needs the real font files; without them the variables are
    // absent and consumers fall back to plain spacing (their `var(..., 0px)`).
    if let Some(fonts) = fonts {
        let insets: Vec<String> = TYPOGRAPHY_FIELDS
            .iter()
            .filter_map(|name| {
                let token = group.get(name)?.get("$value")?;
                let family = token.get("fontFamily")?.as_str()?;
                let weight = token.get("fontWeight")?.as_str()?;
                let ratio = fonts.cap_ratio(family, weight)?;
                let size = token.get("fontSize")?.as_f64()?;
                let line_height = token.get("lineHeight")?.as_f64()?;
                Some(format!(
                    "  --text-optical-inset-{name}: {}px;",
                    fmt_num(((line_height - size * ratio) / 2.0 * 100.0).round() / 100.0)
                ))
            })
            .collect();
        if !insets.is_empty() {
            let _ = writeln!(out, ":root {{\n{}\n}}\n", insets.join("\n"));
        }
    }

    for name in TYPOGRAPHY_FIELDS {
        let token = group
            .get(name)
            .with_context(|| format!("tokens.json: missing typography.{name}"))?;
        let value = token
            .get("$value")
            .with_context(|| format!("typography.{name}: missing $value"))?;

        let family = value
            .get("fontFamily")
            .and_then(Value::as_str)
            .with_context(|| format!("typography.{name}: missing fontFamily"))?;
        let weight_name = value
            .get("fontWeight")
            .and_then(Value::as_str)
            .with_context(|| format!("typography.{name}: missing fontWeight"))?;
        let weight = css_font_weight(weight_name)
            .with_context(|| format!("typography.{name}: unknown fontWeight '{weight_name}'"))?;
        let size = value
            .get("fontSize")
            .and_then(Value::as_f64)
            .with_context(|| format!("typography.{name}: missing fontSize"))?;
        let line_height = value
            .get("lineHeight")
            .and_then(Value::as_f64)
            .with_context(|| format!("typography.{name}: missing lineHeight"))?;
        let tracking = resolve_letter_spacing(tokens, value, name)?;
        let features = family_features(family, fonts);

        let _ = write!(
            out,
            ".t-{name} {{\n  font-family: var(--font-{family});\n  font-weight: {weight};\n  font-size: {}px;\n  line-height: {}px;\n",
            fmt_num(size),
            fmt_num(line_height)
        );
        if tracking != 0.0 {
            let _ = write!(out, "  letter-spacing: {}px;\n", fmt_num(tracking));
        }
        if let Some(text_case) = value.get("textCase").and_then(Value::as_str) {
            let _ = write!(out, "  text-transform: {text_case};\n");
        }
        if !features.is_empty() {
            let settings = features
                .iter()
                .map(|f| format!("\"{}\" {}", f.tag, f.value))
                .collect::<Vec<_>>()
                .join(", ");
            let _ = write!(out, "  font-feature-settings: {settings};\n");
        }
        let _ = write!(out, "}}\n");
    }

    Ok(out)
}

/// Design weight names → CSS numeric weights.
pub fn css_font_weight(weight: &str) -> Result<u16> {
    Ok(match weight {
        "extralight" => 200,
        "light" => 300,
        "regular" => 400,
        "medium" => 500,
        "demibold" => 600,
        "bold" => 700,
        "extrabold" => 800,
        other => anyhow::bail!("unknown fontWeight: '{other}'"),
    })
}

fn family_features(
    family: &str,
    fonts: Option<&InstalledFonts>,
) -> Vec<crate::design::ios::fonts::FontFeature> {
    match fonts {
        Some(installed) => installed.family_features(family).to_vec(),
        None => Vec::new(),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn weight_map() {
        assert_eq!(css_font_weight("regular").unwrap(), 400);
        assert_eq!(css_font_weight("demibold").unwrap(), 600);
        assert!(css_font_weight("black").is_err());
    }
}
