//! Launch screen assets: the background color and the centered Eigin mark,
//! plus the Swift `LaunchMark` they're read through.
//!
//! The launch screen mirrors the first frame of onboarding, so the app can
//! pick up the mark exactly where the launch screen left it. All of it comes
//! from tokens and this one constant, so nothing can drift from anything.

use anyhow::{Context, Result};
use serde_json::Value;
use std::fs;
use std::process::Command;

use super::assets::{colorize_svg, parse_hex_rgb, render_svg, save_rgba, token_hex};

/// The mark's circle diameter in points. Drives both the rendered asset and
/// the generated `LaunchMark.diameter` in the iOS app, so they can't drift.
const MARK_DIAMETER_POINTS: u32 = 128;

/// The brand mark's share of its circle, matching `AppBrandAvatar` (an 8pt
/// inset on a 56pt circle).
const MARK_FILL: f32 = 40.0 / 56.0;

const GENERATED_HEADER: &str =
    "// Generated by eigin-tools — edit tools/src/design/ios/launch.rs, not this file.\n";

const LAUNCH_SWIFT: &str = r#"import SwiftUI

/// The Eigin mark as the launch screen draws it: the brand circle centered on
/// the app background. Onboarding and the launch handoff pick it up from here.
enum LaunchMark {
    /// The circle's diameter in points — the size the launch asset is
    /// rendered at.
    static let diameter: CGFloat = MARK_DIAMETER_PLACEHOLDER

    /// The launch screen's mark, from the generated asset.
    static let image = Image("LaunchMark")

    /// The launch screen's background, from the generated asset.
    static let background = Color("LaunchBackground")
}
"#;

const SCALES: [u32; 3] = [1, 2, 3];

const INFO_JSON: &str = r#""info" : {
    "author" : "xcode",
    "version" : 1
  }"#;

/// Writes `LaunchBackground.colorset` and `LaunchMark.imageset`, each with
/// light and dark appearances.
pub fn generate(repo_root: &str, tokens: &Value) -> Result<()> {
    let catalog = format!("{repo_root}/src/eigin_ios/Resources/Assets.xcassets");
    let logo_path = format!("{repo_root}/design/assets/icons/brand/avatar.svg");
    let logo_svg =
        fs::read_to_string(&logo_path).with_context(|| format!("reading {logo_path}"))?;

    let background_dir = format!("{catalog}/LaunchBackground.colorset");
    fs::create_dir_all(&background_dir).context("creating launch background colorset")?;
    let light_bg = token_hex(tokens, "color.surface.standard.base", "light")?;
    let dark_bg = token_hex(tokens, "color.surface.standard.base", "dark")?;
    fs::write(
        format!("{background_dir}/Contents.json"),
        colorset_json(&light_bg, &dark_bg)?,
    )
    .with_context(|| format!("writing Contents.json to {background_dir}"))?;

    let mark_dir = format!("{catalog}/LaunchMark.imageset");
    fs::create_dir_all(&mark_dir).context("creating launch mark imageset")?;
    for mode in ["light", "dark"] {
        let vessel = token_hex(tokens, "color.surface.impact.base", mode)?;
        let glyph = token_hex(tokens, "color.text.standard.base", mode)?;
        for scale in SCALES {
            let mark = render_mark(&logo_svg, &vessel, &glyph, MARK_DIAMETER_POINTS * scale)?;
            save_rgba(&mark, &format!("{mark_dir}/{}", mark_filename(mode, scale)))
                .context("saving launch mark")?;
        }
    }
    fs::write(format!("{mark_dir}/Contents.json"), imageset_json())
        .with_context(|| format!("writing Contents.json to {mark_dir}"))?;

    let generated_dir = format!("{repo_root}/src/eigin_ios/Sources/Core/Design/Generated");
    let launch_swift_path = format!("{generated_dir}/LaunchMark.swift");
    let launch_swift = LAUNCH_SWIFT.replace(
        "MARK_DIAMETER_PLACEHOLDER",
        &MARK_DIAMETER_POINTS.to_string(),
    );
    fs::write(
        &launch_swift_path,
        format!("{GENERATED_HEADER}{launch_swift}"),
    )
    .with_context(|| format!("writing {launch_swift_path}"))?;
    let status = Command::new("swiftformat")
        .arg(&launch_swift_path)
        .status()
        .context("running swiftformat on LaunchMark.swift")?;
    if !status.success() {
        anyhow::bail!("swiftformat failed on {launch_swift_path}");
    }

    Ok(())
}

/// Draws the green vessel with the brand mark centered on it, on transparency.
fn render_mark(
    logo_svg: &str,
    vessel_hex: &str,
    glyph_hex: &str,
    diameter: u32,
) -> Result<image::RgbaImage> {
    let vessel = format!(
        r#"<svg width="{diameter}" height="{diameter}" viewBox="0 0 {diameter} {diameter}" xmlns="http://www.w3.org/2000/svg"><circle cx="{r}" cy="{r}" r="{r}" fill="{vessel_hex}"/></svg>"#,
        r = diameter as f32 / 2.0
    );
    let mut canvas = render_svg(&vessel, diameter)?;

    let glyph = render_svg(
        &colorize_svg(logo_svg, glyph_hex),
        (diameter as f32 * MARK_FILL).round() as u32,
    )?;
    let x = ((diameter - glyph.width()) / 2) as i64;
    let y = ((diameter - glyph.height()) / 2) as i64;
    image::imageops::overlay(&mut canvas, &glyph, x, y);
    Ok(canvas)
}

fn mark_filename(mode: &str, scale: u32) -> String {
    let suffix = if mode == "dark" { "Dark" } else { "" };
    match scale {
        1 => format!("LaunchMark{suffix}.png"),
        _ => format!("LaunchMark{suffix}@{scale}x.png"),
    }
}

fn imageset_json() -> String {
    let mut images = Vec::new();
    for mode in ["light", "dark"] {
        for scale in SCALES {
            let appearance = if mode == "dark" {
                r#""appearances" : [ { "appearance" : "luminosity", "value" : "dark" } ],
      "#
            } else {
                ""
            };
            images.push(format!(
                r#"    {{
      {appearance}"filename" : "{}",
      "idiom" : "universal",
      "scale" : "{scale}x"
    }}"#,
                mark_filename(mode, scale)
            ));
        }
    }
    format!(
        "{{\n  \"images\" : [\n{}\n  ],\n  {INFO_JSON}\n}}\n",
        images.join(",\n")
    )
}

fn colorset_json(light_hex: &str, dark_hex: &str) -> Result<String> {
    let light = color_json(light_hex)?;
    let dark = color_json(dark_hex)?;
    Ok(format!(
        r#"{{
  "colors" : [
    {{
      "color" : {light},
      "idiom" : "universal"
    }},
    {{
      "appearances" : [ {{ "appearance" : "luminosity", "value" : "dark" }} ],
      "color" : {dark},
      "idiom" : "universal"
    }}
  ],
  {INFO_JSON}
}}
"#
    ))
}

fn color_json(hex: &str) -> Result<String> {
    let [r, g, b] = parse_hex_rgb(hex).with_context(|| format!("parsing launch colour '{hex}'"))?;
    Ok(format!(
        r#"{{ "color-space" : "srgb", "components" : {{ "alpha" : "1.000", "red" : "0x{r:02X}", "green" : "0x{g:02X}", "blue" : "0x{b:02X}" }} }}"#
    ))
}

#[cfg(test)]
mod tests {
    use super::*;

    const SQUARE_SVG: &str = r##"<svg width="10" height="10" viewBox="0 0 10 10" xmlns="http://www.w3.org/2000/svg"><rect width="10" height="10" fill="#000000"/></svg>"##;

    /// The launch screen shows the mark on the background color, so the
    /// corners outside the circle must stay transparent.
    #[test]
    fn mark_is_a_vessel_with_a_centered_glyph_on_transparency() {
        let mark = render_mark(SQUARE_SVG, "#00FF00", "#FF0000", 128).unwrap();

        assert_eq!(mark.dimensions(), (128, 128));
        assert_eq!(mark.get_pixel(0, 0).0[3], 0, "corner is transparent");
        assert_eq!(
            mark.get_pixel(64, 64).0,
            [255, 0, 0, 255],
            "glyph at center"
        );
        assert_eq!(
            mark.get_pixel(64, 4).0,
            [0, 255, 0, 255],
            "vessel around glyph"
        );
    }

    #[test]
    fn colorset_carries_light_and_dark_colors() {
        let json: Value =
            serde_json::from_str(&colorset_json("#F0E0D0", "#102030").unwrap()).unwrap();
        let colors = json["colors"].as_array().unwrap();

        assert_eq!(colors[0]["color"]["components"]["red"], "0xF0");
        assert_eq!(colors[1]["appearances"][0]["value"], "dark");
        assert_eq!(colors[1]["color"]["components"]["blue"], "0x30");
    }

    #[test]
    fn imageset_lists_every_rendition() {
        let json: Value = serde_json::from_str(&imageset_json()).unwrap();
        let images = json["images"].as_array().unwrap();

        assert_eq!(images.len(), 6);
        assert_eq!(images[5]["filename"], "LaunchMarkDark@3x.png");
        assert_eq!(images[5]["appearances"][0]["value"], "dark");
    }
}
