use anyhow::{Context, Result};
use std::collections::BTreeMap;
use std::fmt::Write;
use std::fs;
use std::path::{Path, PathBuf};

const IMAGESET_CONTENTS: &str = r#"{
  "images" : [
    {
      "filename" : "FILENAME",
      "idiom" : "universal"
    }
  ],
  "info" : {
    "author" : "xcode",
    "version" : 1
  },
  "properties" : {
    "preserves-vector-representation" : true,
    "template-rendering-intent" : "template"
  }
}
"#;

const FOLDER_CONTENTS: &str = r#"{
  "info" : {
    "author" : "xcode",
    "version" : 1
  },
  "properties" : {
    "provides-namespace" : true
  }
}
"#;

const SWIFT_HEADER: &str =
    "// Generated by eigin-tools — add SVGs to design/assets/icons/, not this file.\n";

/// Recursively scan `design/assets/icons/` and mirror the folder tree into
/// `Assets.xcassets/Icons/`, generating `Contents.json` for every folder group
/// (namespaced) and every `.imageset` (with vector preservation + template tint).
/// Produces `Sources/Core/Design/Generated/Iconography.swift` as a typed accessor.
pub fn generate(repo_root: &str) -> Result<()> {
    let source_dir = PathBuf::from(repo_root).join("design/assets/icons");
    let asset_dir = PathBuf::from(repo_root).join("src/eigin_ios/Resources/Assets.xcassets/Icons");
    let swift_path = PathBuf::from(repo_root)
        .join("src/eigin_ios/Sources/Core/Design/Generated/Iconography.swift");

    if !source_dir.exists() {
        if asset_dir.exists() {
            fs::remove_dir_all(&asset_dir)
                .with_context(|| format!("removing {}", asset_dir.display()))?;
        }
        if swift_path.exists() {
            fs::remove_file(&swift_path)
                .with_context(|| format!("removing {}", swift_path.display()))?;
        }
        return Ok(());
    }

    // Clean and rebuild asset output
    if asset_dir.exists() {
        fs::remove_dir_all(&asset_dir)
            .with_context(|| format!("clearing {}", asset_dir.display()))?;
    }
    fs::create_dir_all(&asset_dir).with_context(|| format!("creating {}", asset_dir.display()))?;

    let mut tree = IconNode::default();
    process_dir(&source_dir, &source_dir, &asset_dir, &mut tree)?;

    // Delete old ProviderLogos so it doesn't clash with the generated tree
    let old_provider_dir =
        PathBuf::from(repo_root).join("src/eigin_ios/Resources/Assets.xcassets/ProviderLogos");
    if old_provider_dir.exists() {
        fs::remove_dir_all(&old_provider_dir)
            .with_context(|| format!("removing {}", old_provider_dir.display()))?;
    }

    emit_swift(&tree, &swift_path)
}

#[derive(Default, Debug)]
struct IconNode {
    /// stem → dotted asset path (e.g. "openai" → "provider/openai")
    files: BTreeMap<String, String>,
    /// folder name → subtree
    folders: BTreeMap<String, IconNode>,
}

fn process_dir(root: &Path, source: &Path, dest: &Path, node: &mut IconNode) -> Result<()> {
    // Mark this folder as a namespace provider so Xcode builds fully-qualified image names.
    fs::write(dest.join("Contents.json"), FOLDER_CONTENTS)
        .with_context(|| format!("writing Contents.json in {}", dest.display()))?;

    let entries = fs::read_dir(source).with_context(|| format!("reading {}", source.display()))?;

    for entry in entries {
        let entry = entry.with_context(|| format!("reading entry in {}", source.display()))?;
        let path = entry.path();
        let name = entry
            .file_name()
            .into_string()
            .map_err(|_| anyhow::anyhow!("non-utf8 filename in {}", source.display()))?;

        if path.is_dir() {
            let dest_sub = dest.join(&name);
            fs::create_dir_all(&dest_sub)
                .with_context(|| format!("creating {}", dest_sub.display()))?;

            let mut subnode = IconNode::default();
            process_dir(root, &path, &dest_sub, &mut subnode)?;
            if !subnode.files.is_empty() || !subnode.folders.is_empty() {
                node.folders.insert(name, subnode);
            }
        } else if path.extension().and_then(|s| s.to_str()) == Some("svg") {
            let stem = Path::new(&name)
                .file_stem()
                .unwrap()
                .to_str()
                .unwrap()
                .to_string();

            let imageset_name = format!("{}.imageset", stem);
            let imageset_dir = dest.join(&imageset_name);
            fs::create_dir(&imageset_dir)
                .with_context(|| format!("creating {}", imageset_dir.display()))?;

            let dest_svg = imageset_dir.join(&name);
            fs::copy(&path, &dest_svg)
                .with_context(|| format!("copying {} to {}", path.display(), dest_svg.display()))?;

            let contents = IMAGESET_CONTENTS.replace("FILENAME", &name);
            fs::write(imageset_dir.join("Contents.json"), contents)
                .with_context(|| format!("writing Contents.json in {}", imageset_dir.display()))?;

            let relative = path.strip_prefix(root).unwrap().with_extension("");
            let asset_path = relative
                .to_str()
                .unwrap()
                .replace(std::path::MAIN_SEPARATOR, "/");
            node.files.insert(stem, asset_path);
        }
    }

    Ok(())
}

fn emit_swift(node: &IconNode, path: &Path) -> Result<()> {
    let mut out = String::from(SWIFT_HEADER);
    out.push_str("import SwiftUI\n\n");
    out.push_str(
        "/// App icons generated from design/assets/icons/. Mirror design folder structure when adding.\n",
    );
    out.push_str("enum Iconography {\n");
    write_swift_body(node, &mut out, 1)?;
    out.push_str("}\n");

    let parent = path.parent().unwrap();
    fs::create_dir_all(parent).with_context(|| format!("creating {}", parent.display()))?;
    fs::write(path, out).with_context(|| format!("writing {}", path.display()))
}

fn write_swift_body(node: &IconNode, out: &mut String, depth: usize) -> Result<()> {
    let indent = "    ".repeat(depth);

    for (folder_name, subnode) in &node.folders {
        let type_name = swift_type_name(&to_camel_case(folder_name));
        writeln!(out, "{indent}enum {type_name} {{").unwrap();
        write_swift_body(subnode, out, depth + 1)?;
        writeln!(out, "{indent}}}").unwrap();
    }

    for (stem, asset_path) in &node.files {
        let prop = to_camel_case(stem);
        writeln!(
            out,
            "{indent}static let {prop} = Image(\"Icons/{asset_path}\")"
        )
        .unwrap();
    }

    Ok(())
}

fn swift_type_name(name: &str) -> String {
    let mut chars = name.chars();
    match chars.next() {
        None => String::new(),
        Some(c) => c.to_uppercase().collect::<String>() + chars.as_str(),
    }
}

/// snake_case or kebab-case → camelCase (first char lowercased).
fn to_camel_case(s: &str) -> String {
    let mut result = String::new();
    let mut upper_next = false;
    for (i, c) in s.chars().enumerate() {
        if c == '_' || c == '-' {
            upper_next = true;
        } else if i == 0 {
            result.push(c.to_lowercase().next().unwrap_or(c));
        } else if upper_next {
            result.push(c.to_uppercase().next().unwrap_or(c));
            upper_next = false;
        } else {
            result.push(c);
        }
    }
    result
}
