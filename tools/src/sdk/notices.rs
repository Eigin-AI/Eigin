//! Shared notices for the SDK's normal dependency graph and browser runtimes.

use anyhow::{Context, Result, bail, ensure};
use serde_json::Value;
use std::collections::{BTreeMap, BTreeSet};
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

const OUTPUTS: &[&str] = &[
    "src/eigin_sdk/THIRD-PARTY-NOTICES.txt",
    "src/eigin_sdk/apple/EiginSDK/Sources/EiginSDK/Resources/THIRD-PARTY-NOTICES.txt",
    "src/eigin_sdk/web/THIRD-PARTY-NOTICES.txt",
    "src/eigin_web/public/SDK-NOTICES.txt",
];

struct Entry {
    name: String,
    version: String,
    license: String,
    repository: String,
    ecosystem: String,
    attribution: String,
    notice: String,
    licenses: Vec<(String, String)>,
}

/// Regenerate notices, or fail if any committed copy differs from resolved dependencies.
pub fn generate(root: &str, check: bool) -> Result<()> {
    let root = Path::new(root);
    let mut entries = BTreeMap::new();
    for (manifest, targets) in [
        (
            "src/eigin_sdk/Cargo.toml",
            vec![
                "aarch64-apple-ios",
                "aarch64-apple-darwin",
                "x86_64-apple-darwin",
                "wasm32-unknown-unknown",
            ],
        ),
        (
            "src/eigin_cli/Cargo.toml",
            vec![
                "aarch64-apple-darwin",
                "x86_64-unknown-linux-gnu",
                "x86_64-pc-windows-msvc",
            ],
        ),
    ] {
        let manifest = root.join(manifest);
        let metadata: Value =
            serde_json::from_str(&cargo(&manifest, &["metadata", "--format-version", "1"])?)?;
        let mut selected = BTreeSet::new();
        for target in targets {
            let tree = cargo(
                &manifest,
                &[
                    "tree",
                    "-p",
                    "eigin_sdk",
                    "--target",
                    target,
                    "--edges",
                    "normal,no-proc-macro",
                    "--prefix",
                    "none",
                    "--format",
                    "{p}",
                ],
            )?;
            selected.extend(tree.lines().filter_map(|line| {
                let mut parts = line.split_whitespace();
                Some((
                    parts.next()?.to_owned(),
                    parts.next()?.trim_start_matches('v').to_owned(),
                ))
            }));
        }
        for package in metadata["packages"]
            .as_array()
            .context("Cargo packages missing")?
        {
            let name = string(package, "name")?;
            let version = string(package, "version")?;
            if !selected.remove(&(name.into(), version.into())) || name == "eigin_sdk" {
                continue;
            }
            let directory = Path::new(string(package, "manifest_path")?)
                .parent()
                .unwrap();
            let text = entry(
                root,
                "Cargo",
                name,
                version,
                string(package, "license")?,
                package["repository"].as_str().unwrap_or(""),
                directory,
            )?;
            entries.insert(format!("Cargo {name} {version}"), text);
        }
        ensure!(
            selected.is_empty(),
            "Runtime packages missing from Cargo metadata: {selected:?}"
        );
    }
    let lock: Value = serde_json::from_str(&fs::read_to_string(root.join("package-lock.json"))?)?;
    let mut visited = BTreeSet::new();
    npm_entries(root, &lock, "src/eigin_sdk/web", &mut visited, &mut entries)?;
    let mut output = String::from(
        "Eigin SDK — third-party notices\n\nGenerated by `just sdk-notices`. Do not edit.\n\nIncludes the union of SDK runtime dependencies for Apple, WebAssembly, and\nCLI (macOS, Linux, Windows), plus browser runtime packages. Host application\ndependencies are separate. Build, test and procedural-macro dependencies\nare excluded. Versions are resolved from the SDK, CLI and npm lockfiles.\nSome dependencies apply only to particular platforms.\nPackage entries reference the full license texts collected below.\nIdentical texts are included once, with their copyright notices intact.\n\n",
    );
    let mut shared_texts: Vec<&str> = Vec::new();
    let mut packages = Vec::new();
    for entry in entries.values() {
        output.push_str(&entry.notice);
        let mut license_ids = Vec::new();
        for (label, body) in &entry.licenses {
            let index = shared_texts
                .iter()
                .position(|text| *text == body)
                .unwrap_or_else(|| {
                    shared_texts.push(body);
                    shared_texts.len() - 1
                });
            output.push_str(&format!("{label}: see license text {} below.\n", index + 1));
            license_ids.push(index);
        }
        packages.push(serde_json::json!({
            "name": entry.name, "version": entry.version, "license": entry.license,
            "repository": entry.repository.trim_start_matches("git+"), "ecosystem": entry.ecosystem,
            "notice": entry.attribution.trim(), "licenseIds": license_ids
        }));
        output.push('\n');
    }
    output.push_str("SHARED LICENSE TEXTS\n\n");
    for (index, text) in shared_texts.iter().enumerate() {
        output.push_str(&format!("================================================================\nLicense text {}\n\n{text}\n\n", index + 1));
    }
    output.truncate(output.trim_end().len());
    output.push('\n');
    let config: toml::Value = toml::from_str(&fs::read_to_string(root.join("config/app.toml"))?)?;
    let version = config["version"]["sdk"]
        .as_str()
        .context("Missing SDK version")?;
    let sdk_license = license_text(&root.join("LICENSE"))?;
    let sdk_license_id = shared_texts.len();
    shared_texts.push(&sdk_license);
    let catalog = serde_json::json!({
        "sdk": {"name": "Eigin SDK", "version": version, "license": "AGPL-3.0",
            "repository": "https://code.eigin.ai/dev/eigin", "ecosystem": "",
            "notice": "", "licenseIds": [sdk_license_id]},
        "packages": packages, "licenseTexts": shared_texts
    });
    let json = serde_json::to_string_pretty(&catalog)? + "\n";
    let outputs = OUTPUTS.iter().map(|path| (*path, &output)).chain([
        ("src/eigin_sdk/NOTICES.json", &json),
        (
            "src/eigin_sdk/apple/EiginSDK/Sources/EiginSDK/Resources/NOTICES.json",
            &json,
        ),
    ]);
    // Validate everything before writing any output.
    for (path, content) in outputs {
        let path = root.join(path);
        if fs::read_to_string(&path).ok().as_deref() == Some(content) {
            continue;
        }
        ensure!(
            !check,
            "Stale SDK notices: {}. Run just sdk-notices",
            path.display()
        );
        fs::create_dir_all(path.parent().unwrap())?;
        fs::write(path, content)?;
    }
    Ok(())
}

fn cargo(manifest: &Path, args: &[&str]) -> Result<String> {
    let output = Command::new("cargo")
        .args(args)
        .arg("--locked")
        .arg("--manifest-path")
        .arg(manifest)
        .current_dir(manifest.parent().unwrap())
        .env_remove("RUSTUP_TOOLCHAIN")
        .output()?;
    ensure!(
        output.status.success(),
        "cargo failed: {}",
        String::from_utf8_lossy(&output.stderr)
    );
    Ok(String::from_utf8(output.stdout)?)
}

fn string<'a>(value: &'a Value, key: &str) -> Result<&'a str> {
    value[key]
        .as_str()
        .with_context(|| format!("Missing {key}: {value}"))
}

fn npm_entries(
    root: &Path,
    lock: &Value,
    path: &str,
    visited: &mut BTreeSet<String>,
    entries: &mut BTreeMap<String, Entry>,
) -> Result<()> {
    if !visited.insert(path.into()) {
        return Ok(());
    }
    let package = &lock["packages"][path];
    ensure!(package.is_object(), "Missing locked npm package {path}");
    if path.contains("node_modules/") {
        let directory = root.join(path);
        let installed: Value = serde_json::from_str(
            &fs::read_to_string(directory.join("package.json"))
                .context("Run npm ci before generating SDK notices")?,
        )?;
        let name = string(&installed, "name")?;
        let version = string(package, "version")?;
        ensure!(installed["version"] == version, "Run npm ci: stale {name}");
        let repository = installed["repository"]["url"]
            .as_str()
            .or(installed["repository"].as_str())
            .unwrap_or("");
        entries.insert(
            format!("npm {name} {version}"),
            entry(
                root,
                "npm",
                name,
                version,
                string(&installed, "license")?,
                repository,
                &directory,
            )?,
        );
    }
    for kind in ["dependencies", "optionalDependencies", "peerDependencies"] {
        if let Some(dependencies) = package[kind].as_object() {
            for name in dependencies.keys() {
                let mut parent = Some(Path::new(path));
                let mut resolved = None;
                while let Some(base) = parent {
                    let candidate = base
                        .join("node_modules")
                        .join(name)
                        .to_string_lossy()
                        .into_owned();
                    if lock["packages"][&candidate].is_object() {
                        resolved = Some(candidate);
                        break;
                    }
                    parent = base.parent();
                }
                let resolved = resolved.with_context(|| {
                    format!("Unresolved npm runtime dependency {name} from {path}")
                })?;
                npm_entries(root, lock, &resolved, visited, entries)?;
            }
        }
    }
    Ok(())
}

fn entry(
    root: &Path,
    ecosystem: &str,
    name: &str,
    version: &str,
    license: &str,
    repository: &str,
    directory: &Path,
) -> Result<Entry> {
    let mut licenses = Vec::new();
    let mut text = format!(
        "================================================================\n{name} {version} ({ecosystem})\nLicense: {license}\nSource: {repository}\n\n"
    );
    let mut files: Vec<PathBuf> = fs::read_dir(directory)?
        .map(|entry| entry.map(|e| e.path()))
        .collect::<std::io::Result<_>>()?;
    files.retain(|path| {
        path.is_file() && is_notice(path.file_name().unwrap().to_str().unwrap_or(""))
    });
    files.sort();
    if matches!(license, "MIT OR Apache-2.0" | "Apache-2.0 OR MIT") {
        ensure!(
            files.iter().any(|path| path
                .file_name()
                .unwrap()
                .eq_ignore_ascii_case("LICENSE-MIT")),
            "Missing MIT license text for {name} {version}"
        );
        files.retain(|path| {
            let name = path
                .file_name()
                .unwrap()
                .to_string_lossy()
                .to_ascii_uppercase();
            !matches!(name.as_str(), "LICENSE-APACHE" | "LICENSE-APACHE-2.0")
        });
        text.push_str("Selected license: MIT\n\n");
    }
    let notice_start = text.len();
    let has_license = files
        .iter()
        .any(|path| is_license(&path.file_name().unwrap().to_string_lossy()));
    if !has_license {
        let source = match (name, version, license) {
            ("uniffi" | "uniffi_core" | "uniffi_pipeline", "0.31.0", "MPL-2.0") => {
                "https://github.com/mozilla/uniffi-rs/tree/v0.31.0"
            }
            ("uniffi-runtime-wasm" | "@ubjs/core" | "@ubjs/wasm", "0.31.0-6", "MPL-2.0") => {
                "https://github.com/jhugman/uniffi-bindgen-react-native/tree/0.31.0-6"
            }
            _ => bail!(
                "No license text for {name} {version}; add a reviewed, version-pinned source notice"
            ),
        };
        text.push_str(&format!("Unmodified MPL-covered source is available at {source}.\n\nThis Source Code Form is subject to the terms of the Mozilla Public\nLicense, v. 2.0. If a copy of the MPL was not distributed with this\nfile, You can obtain one at http://mozilla.org/MPL/2.0/.\n\n"));
        licenses.push((
            "MPL-2.0".into(),
            license_text(&root.join("LICENSES/uniffi/MPL-2.0.txt"))?,
        ));
    }
    for path in files {
        let label = path.file_name().unwrap().to_string_lossy().into_owned();
        if is_license(&label) {
            licenses.push((label, license_text(&path)?));
        } else {
            let body = fs::read_to_string(&path)?;
            text.push_str(&format!("--- {label} ---\n{body}\n\n"));
        }
    }
    Ok(Entry {
        name: name.into(),
        version: version.into(),
        repository: repository.into(),
        ecosystem: ecosystem.into(),
        license: if matches!(license, "MIT OR Apache-2.0" | "Apache-2.0 OR MIT") {
            "MIT"
        } else {
            license
        }
        .into(),
        attribution: text[notice_start..].to_owned(),
        notice: text,
        licenses,
    })
}

fn license_text(path: &Path) -> Result<String> {
    let text = fs::read_to_string(path)?;
    ensure!(
        !text.trim().is_empty(),
        "Empty license text: {}",
        path.display()
    );
    Ok(text)
}

fn is_license(name: &str) -> bool {
    let name = name.to_ascii_uppercase();
    ["LICENSE", "LICENCE", "COPYING", "UNLICENSE"]
        .iter()
        .any(|prefix| name.starts_with(prefix))
}

fn is_notice(name: &str) -> bool {
    let name = name.to_ascii_uppercase();
    is_license(&name)
        || ["COPYRIGHT", "NOTICE", "AUTHORS"]
            .iter()
            .any(|prefix| name.starts_with(prefix))
}

