use crate::codegen::ios::{camel_case, pascal_case, swift_ident_escape};
use anyhow::{Result, bail};
use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write;

pub use eigin_prompt_template::Templates;

/// Resolve parameters using the same include validation as runtime loading.
pub fn resolve_all_params(templates: &Templates) -> Result<BTreeMap<String, Vec<String>>> {
    eigin_prompt_template::resolve_all_params(templates).map_err(anyhow::Error::msg)
}

/// Emit typed Swift accessors forwarding to the embedded SDK catalog.
pub fn emit(templates: &Templates) -> Result<String> {
    let params = resolve_all_params(templates)?;
    let mut tree = Node::default();
    let mut symbols = BTreeSet::from(["Prompt.catalog".to_owned(), "Prompt.render".to_owned()]);
    let mut folders = BTreeMap::new();
    for path in templates.keys() {
        let parts: Vec<_> = path.split('/').collect();
        for depth in 1..parts.len() {
            let original = parts[..depth].join("/");
            let normalized = parts[..depth]
                .iter()
                .map(|part| pascal_case(part))
                .collect::<Vec<_>>()
                .join(".");
            if let Some(previous) = folders.insert(normalized, original.clone()) {
                if previous != original {
                    bail!("normalized Swift folder collision: {previous} and {original}");
                }
            }
        }
        let name = symbol(path);
        if !symbols.insert(name.clone()) {
            bail!("duplicate Swift prompt accessor: {name}");
        }
        tree.insert(path)?;
    }
    let mut out = String::from(
        "// Generated by eigin-tools — edit design/prompts/, not this file.\n// swiftformat:disable all\nextension EiginSDK {\n    /// Typed accessors for the SDK's embedded Eigin prompt catalog.\n    public enum DefaultPrompts {\n",
    );
    out.push_str("        private static let catalog = EiginSDK.PromptCatalog.defaultCatalog()\n\n        private static func render(_ name: String, _ parameters: [String: String]) -> String {\n            do {\n                return try catalog.render(name: name, parameters: parameters)\n            } catch {\n                preconditionFailure(\"Bundled prompt contract failed for \\(name): \\(error)\")\n            }\n        }\n\n");
    write_body(&tree, &params, &mut out, 2);
    out.push_str("    }\n}\n");
    Ok(out)
}

#[derive(Default)]
struct Node {
    folders: BTreeMap<String, Node>,
    files: BTreeMap<String, String>,
}

impl Node {
    fn insert(&mut self, path: &str) -> Result<()> {
        let components: Vec<_> = path.trim_end_matches(".jinja").split('/').collect();
        let mut node = self;
        for folder in &components[..components.len() - 1] {
            let ident = pascal_case(folder);
            if node.files.contains_key(&ident) {
                bail!("Swift namespace collision: {path}");
            }
            node = node.folders.entry(ident).or_default();
        }
        let name = swift_ident_escape(&camel_case(components.last().unwrap()));
        if node.folders.contains_key(&name) || node.files.insert(name, path.into()).is_some() {
            bail!("Swift accessor collision: {path}");
        }
        Ok(())
    }
}

fn write_body(node: &Node, params: &BTreeMap<String, Vec<String>>, out: &mut String, depth: usize) {
    let indent = "    ".repeat(depth);
    for (folder, sub) in &node.folders {
        writeln!(
            out,
            "{indent}/// {folder} prompt templates.\n{indent}public enum {folder} {{"
        )
        .unwrap();
        write_body(sub, params, out, depth + 1);
        writeln!(out, "{indent}}}\n").unwrap();
    }
    for (name, source) in &node.files {
        let parameters = &params[source];
        let values = parameters
            .iter()
            .map(|p| format!("{}: {}", quote(p), swift_ident_escape(p)))
            .collect::<Vec<_>>()
            .join(", ");
        let values = if parameters.is_empty() {
            ":".into()
        } else {
            values
        };
        let call = format!(
            "EiginSDK.DefaultPrompts.render({}, [{values}])",
            quote(source)
        );
        if parameters.is_empty() {
            writeln!(
                out,
                "{indent}/// Renders `{source}`.\n{indent}public static let {name} = {call}\n"
            )
            .unwrap();
        } else {
            let signature = parameters
                .iter()
                .map(|p| format!("{}: String", swift_ident_escape(p)))
                .collect::<Vec<_>>()
                .join(", ");
            writeln!(out, "{indent}/// Renders `{source}`.\n{indent}public static func {name}({signature}) -> String {{\n{indent}    {call}\n{indent}}}\n").unwrap();
        }
    }
}

/// A path-derived accessor using the app's `Prompt` alias.
pub(crate) fn symbol(rel: &str) -> String {
    let stem = rel.trim_end_matches(".jinja");
    let parts: Vec<_> = stem.split('/').collect();
    let mut out = String::from("Prompt");
    for folder in &parts[..parts.len() - 1] {
        write!(out, ".{}", pascal_case(folder)).unwrap();
    }
    write!(
        out,
        ".{}",
        swift_ident_escape(&camel_case(parts.last().unwrap()))
    )
    .unwrap();
    out
}

/// Fully qualified SDK accessor for use outside the SDK module.
pub(crate) fn sdk_symbol(rel: &str) -> String {
    symbol(rel).replacen("Prompt.", "EiginSDK.DefaultPrompts.", 1)
}

pub(crate) fn quote(value: &str) -> String {
    serde_json::to_string(value).unwrap()
}

#[cfg(test)]
mod tests {
    use super::super::parser::parse;
    use super::*;

    #[test]
    fn forwards_static_and_dynamic_accessors_without_prompt_bodies() {
        let templates = BTreeMap::from([
            ("a/static.jinja".into(), parse("private wording").unwrap()),
            (
                "a/dynamic.jinja".into(),
                parse("{% if name %}{{ name }}{% endif %}").unwrap(),
            ),
        ]);
        let swift = emit(&templates).unwrap();
        assert!(swift.contains(
            "public static let `static` = EiginSDK.DefaultPrompts.render(\"a/static.jinja\", [:])"
        ));
        assert!(swift.contains("public static func dynamic(name: String) -> String"));
        assert!(swift.contains("public enum DefaultPrompts"));
        assert!(swift.contains("public enum A"));
        assert!(!swift.contains("import EiginSDK"));
        assert!(!swift.contains("private wording"));
        assert!(!swift.contains("isEmpty"));
    }

    #[test]
    fn rejects_normalized_name_collisions() {
        let templates =
            BTreeMap::from([("a_b.jinja".into(), vec![]), ("a-b.jinja".into(), vec![])]);
        assert!(emit(&templates).is_err());
    }
}
