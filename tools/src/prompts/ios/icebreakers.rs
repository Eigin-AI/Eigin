use anyhow::{Context, Result, bail};
use serde::Deserialize;
use std::collections::BTreeSet;
use std::fmt::Write;
use std::fs;
use std::path::Path;

/// A use-case group of icebreakers, parsed from one `*.toml` manifest under
/// `design/prompts/icebreakers/`.
pub struct Group {
    pub id: String,
    pub label: Localized,
    pub featured: bool,
    pub order: i64,
    pub icebreakers: Vec<Icebreaker>,
}

pub struct Icebreaker {
    pub id: String,
    pub title: Localized,
    pub prompt: Localized,
}

pub struct Localized {
    pub en: String,
    pub da: String,
}

#[derive(Deserialize)]
struct GroupToml {
    id: String,
    label: LocalizedToml,
    #[serde(default)]
    featured: bool,
    #[serde(default)]
    order: i64,
    #[serde(default, rename = "icebreaker")]
    icebreakers: Vec<IcebreakerToml>,
}

#[derive(Deserialize)]
struct IcebreakerToml {
    id: String,
    title: LocalizedToml,
    prompt: LocalizedToml,
}

#[derive(Deserialize)]
struct LocalizedToml {
    en: String,
    da: String,
}

/// Parse every `design/prompts/icebreakers/*.toml` manifest into a group. The
/// directory is optional — a repo without icebreakers yields an empty list (and
/// an empty registry). Groups are returned sorted by id for stable output.
pub fn collect(source_dir: &Path) -> Result<Vec<Group>> {
    let dir = source_dir.join("icebreakers");
    if !dir.exists() {
        return Ok(Vec::new());
    }

    let mut groups = Vec::new();
    for entry in fs::read_dir(&dir).with_context(|| format!("reading {}", dir.display()))? {
        let path = entry?.path();
        if path.extension().and_then(|s| s.to_str()) != Some("toml") {
            continue;
        }
        groups.push(parse_manifest(&path)?);
    }
    groups.sort_by(|a, b| a.id.cmp(&b.id));
    Ok(groups)
}

fn parse_manifest(path: &Path) -> Result<Group> {
    let source = fs::read_to_string(path).with_context(|| format!("reading {}", path.display()))?;
    let manifest: GroupToml =
        toml::from_str(&source).with_context(|| format!("parsing {}", path.display()))?;

    if manifest.icebreakers.is_empty() {
        bail!(
            "icebreaker group `{}` in {} has no icebreakers",
            manifest.id,
            path.display()
        );
    }

    let mut seen = BTreeSet::new();
    for ice in &manifest.icebreakers {
        if !seen.insert(ice.id.as_str()) {
            bail!(
                "icebreaker id `{}` is declared twice in {}",
                ice.id,
                path.display()
            );
        }
    }

    Ok(Group {
        id: manifest.id,
        label: manifest.label.into(),
        featured: manifest.featured,
        order: manifest.order,
        icebreakers: manifest
            .icebreakers
            .into_iter()
            .map(|i| Icebreaker {
                id: i.id,
                title: i.title.into(),
                prompt: i.prompt.into(),
            })
            .collect(),
    })
}

impl From<LocalizedToml> for Localized {
    fn from(t: LocalizedToml) -> Self {
        Localized { en: t.en, da: t.da }
    }
}

/// Emit `IcebreakerRegistry.swift` from the parsed groups, validating that group
/// ids are globally unique across manifests.
pub fn emit(groups: &[Group]) -> Result<String> {
    let mut ids = BTreeSet::new();
    for group in groups {
        if !ids.insert(group.id.as_str()) {
            bail!(
                "icebreaker group id `{}` is declared by more than one manifest",
                group.id
            );
        }
    }

    let mut out = String::from(
        "// Generated by eigin-tools — edit design/prompts/icebreakers/*.toml, not this file.\n",
    );
    out.push_str("import Foundation\n\n");
    out.push_str(
        "/// Icebreakers declared in design/prompts/icebreakers/*.toml. Edit the manifests, not this file.\n",
    );
    out.push_str("enum IcebreakerRegistry {\n");
    out.push_str("    static let all: [IcebreakerGroup] = [\n");
    for group in groups {
        writeln!(out, "        IcebreakerGroup(").unwrap();
        writeln!(out, "            id: \"{}\",", escape(&group.id)).unwrap();
        writeln!(out, "            label: {},", localized(&group.label)).unwrap();
        writeln!(out, "            featured: {},", group.featured).unwrap();
        writeln!(out, "            order: {},", group.order).unwrap();
        writeln!(out, "            icebreakers: [").unwrap();
        for ice in &group.icebreakers {
            writeln!(
                out,
                "                IcebreakerPrompt(id: \"{}\", title: {}, prompt: {}),",
                escape(&ice.id),
                localized(&ice.title),
                localized(&ice.prompt)
            )
            .unwrap();
        }
        writeln!(out, "            ]\n        ),").unwrap();
    }
    out.push_str("    ]\n");
    out.push_str("}\n");
    Ok(out)
}

fn localized(value: &Localized) -> String {
    format!(
        "LocalizedText(en: \"{}\", da: \"{}\")",
        escape(&value.en),
        escape(&value.da)
    )
}

/// Escape a string for embedding inside a single-line Swift `"..."` literal.
fn escape(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for c in s.chars() {
        match c {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            '\0' => out.push_str("\\0"),
            _ => out.push(c),
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    fn group(toml: &str) -> Group {
        let manifest: GroupToml = toml::from_str(toml).unwrap();
        Group {
            id: manifest.id,
            label: manifest.label.into(),
            featured: manifest.featured,
            order: manifest.order,
            icebreakers: manifest
                .icebreakers
                .into_iter()
                .map(|i| Icebreaker {
                    id: i.id,
                    title: i.title.into(),
                    prompt: i.prompt.into(),
                })
                .collect(),
        }
    }

    const SAMPLE: &str = r#"
id = "get_organized"
label.en = "Get organized"
label.da = "Bliv organiseret"
featured = true
order = 20

[[icebreaker]]
id = "plan_week"
title.en = "Plan my week"
title.da = "Planlæg min uge"
prompt.en = "Help me plan my week."
prompt.da = "Hjælp mig med at planlægge ugen."
"#;

    #[test]
    fn emits_group_and_localized_fields() {
        let swift = emit(&[group(SAMPLE)]).unwrap();
        assert!(swift.contains("enum IcebreakerRegistry {"));
        assert!(swift.contains("static let all: [IcebreakerGroup] = ["));
        assert!(swift.contains("id: \"get_organized\""));
        assert!(
            swift.contains("label: LocalizedText(en: \"Get organized\", da: \"Bliv organiseret\")")
        );
        assert!(swift.contains("featured: true"));
        assert!(swift.contains("order: 20"));
        assert!(swift.contains(
            "IcebreakerPrompt(id: \"plan_week\", title: LocalizedText(en: \"Plan my week\", da: \"Planlæg min uge\"), prompt: LocalizedText(en: \"Help me plan my week.\", da: \"Hjælp mig med at planlægge ugen.\"))"
        ));
    }

    #[test]
    fn defaults_featured_and_order() {
        let swift = emit(&[group(
            r#"
id = "learn"
label.en = "Learn"
label.da = "Lær"

[[icebreaker]]
id = "explain"
title.en = "Explain a topic"
title.da = "Forklar et emne"
prompt.en = "Explain something to me."
prompt.da = "Forklar noget for mig."
"#,
        )])
        .unwrap();
        assert!(swift.contains("featured: false"));
        assert!(swift.contains("order: 0"));
    }

    #[test]
    fn escapes_quotes_and_newlines() {
        let swift = emit(&[group(
            r#"
id = "x"
label.en = "X"
label.da = "X"

[[icebreaker]]
id = "y"
title.en = "Say \"hi\""
title.da = "Sig \"hej\""
prompt.en = "Line one.\nLine two."
prompt.da = "Linje et.\nLinje to."
"#,
        )])
        .unwrap();
        assert!(swift.contains(r#"title: LocalizedText(en: "Say \"hi\"", da: "Sig \"hej\"")"#));
        assert!(swift.contains(r#"en: "Line one.\nLine two.""#));
    }

    #[test]
    fn duplicate_group_ids_error() {
        let err = emit(&[group(SAMPLE), group(SAMPLE)]).unwrap_err();
        assert!(err.to_string().contains("more than one manifest"));
    }
}
