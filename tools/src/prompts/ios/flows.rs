use super::generator::{self, Templates};
use anyhow::{Context, Result, bail};
use serde::Deserialize;
use std::collections::BTreeMap;
use std::fs;
use std::path::{MAIN_SEPARATOR, Path};

/// A flow, resolved against the compiled template tree: each stage's
/// `instructions` path is checked to exist and to take no template
/// variables (notes are supplied by the flow tool at runtime, not the
/// template), and resolved to its generated `Prompt.*` symbol.
pub struct Flow {
    pub name: String,
    pub skill_id: String,
    pub stages: Vec<Stage>,
}

pub struct Stage {
    pub name: String,
    pub symbol: String,
    pub show_notes: bool,
}

#[derive(Deserialize)]
struct FlowsToml {
    #[serde(default)]
    flows: Vec<FlowToml>,
}

#[derive(Deserialize)]
struct FlowToml {
    name: String,
    #[serde(default)]
    stages: Vec<StageToml>,
}

#[derive(Deserialize)]
struct StageToml {
    name: String,
    instructions: String,
    #[serde(default)]
    show_notes: bool,
}

/// Recursively find every `flows.toml` under `dir`, parse it, and resolve each
/// stage's `instructions` path against the compiled template tree. The owning
/// skill id is derived from the manifest's parent directory name (e.g.
/// `design/prompts/skills/planning/flows.toml` → skill id `planning`).
pub fn collect(
    root: &Path,
    dir: &Path,
    templates: &Templates,
    params: &BTreeMap<String, Vec<String>>,
    flows: &mut Vec<Flow>,
) -> Result<()> {
    for entry in fs::read_dir(dir).with_context(|| format!("reading {}", dir.display()))? {
        let path = entry?.path();
        if path.is_dir() {
            collect(root, &path, templates, params, flows)?;
        } else if path.file_name().and_then(|s| s.to_str()) == Some("flows.toml") {
            collect_manifest(root, &path, templates, params, flows)?;
        }
    }
    Ok(())
}

fn collect_manifest(
    root: &Path,
    path: &Path,
    templates: &Templates,
    params: &BTreeMap<String, Vec<String>>,
    flows: &mut Vec<Flow>,
) -> Result<()> {
    let skill_id = path
        .parent()
        .and_then(|p| p.file_name())
        .and_then(|s| s.to_str())
        .ok_or_else(|| anyhow::anyhow!("cannot derive skill id for {}", path.display()))?
        .to_string();

    let source = fs::read_to_string(path).with_context(|| format!("reading {}", path.display()))?;
    let manifest: FlowsToml =
        toml::from_str(&source).with_context(|| format!("parsing {}", path.display()))?;

    let dir_rel = path.parent().unwrap().strip_prefix(root).unwrap();

    for flow in manifest.flows {
        if flow.stages.is_empty() {
            bail!("flow `{}` in {} has no stages", flow.name, path.display());
        }
        let mut stages = Vec::new();
        for stage in flow.stages {
            let instructions_rel = dir_rel
                .join(&stage.instructions)
                .to_str()
                .ok_or_else(|| anyhow::anyhow!("non-utf8 path in {}", path.display()))?
                .replace(MAIN_SEPARATOR, "/");

            if !templates.contains_key(&instructions_rel) {
                bail!(
                    "flow `{}` stage `{}` in {} references unknown template `{}`",
                    flow.name,
                    stage.name,
                    path.display(),
                    instructions_rel
                );
            }
            if !params[&instructions_rel].is_empty() {
                bail!(
                    "flow stage template `{instructions_rel}` must not take variables — notes are supplied by the flow tool at runtime, not the template"
                );
            }

            stages.push(Stage {
                name: stage.name,
                symbol: generator::symbol(&instructions_rel),
                show_notes: stage.show_notes,
            });
        }
        flows.push(Flow {
            name: flow.name,
            skill_id: skill_id.clone(),
            stages,
        });
    }

    Ok(())
}

/// Emit `FlowRegistry.swift` from the resolved flows, validating that flow
/// names are globally unique across skills.
pub fn emit(flows: &[Flow]) -> Result<String> {
    let mut owners: BTreeMap<&str, &str> = BTreeMap::new();
    for flow in flows {
        if let Some(existing) = owners.insert(&flow.name, &flow.skill_id) {
            bail!(
                "flow name `{}` is declared by both `{}` and `{}` — flow names must be globally unique",
                flow.name,
                existing,
                flow.skill_id
            );
        }
    }

    let mut sorted: Vec<&Flow> = flows.iter().collect();
    sorted.sort_by(|a, b| a.name.cmp(&b.name));

    let mut out = String::from(
        "// Generated by eigin-tools — edit design/prompts/**/flows.toml, not this file.\n",
    );
    out.push_str("import Foundation\n\n");
    out.push_str(
        "/// Flows declared in design/prompts/**/flows.toml. Edit the manifests, not this file.\n",
    );
    out.push_str("enum FlowRegistry {\n");
    out.push_str("    static let all: [String: FlowDefinition] = [\n");
    for flow in &sorted {
        out.push_str(&format!(
            "        \"{}\": FlowDefinition(\n            name: \"{}\",\n            skillID: \"{}\",\n            stages: [\n",
            flow.name, flow.name, flow.skill_id
        ));
        for stage in &flow.stages {
            out.push_str(&format!(
                "                FlowStageDefinition(name: \"{}\", render: {{ {} }}, showNotes: {}),\n",
                stage.name, stage.symbol, stage.show_notes
            ));
        }
        out.push_str("            ]\n        ),\n");
    }
    out.push_str("    ]\n");
    out.push_str("}\n");
    Ok(out)
}
