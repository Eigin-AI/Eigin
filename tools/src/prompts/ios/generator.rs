use super::parser::Segment;
use crate::codegen::ios::{camel_case, pascal_case, swift_ident_escape};
use anyhow::{Result, anyhow, bail};
use std::collections::BTreeMap;
use std::fmt::Write;

const HEADER: &str = "// Generated by eigin-tools — edit design/prompts/*.jinja, not this file.\n";

/// A parsed template keyed by its path relative to `design/prompts/`
/// (e.g. `"system/behavioral.jinja"`).
pub type Templates = BTreeMap<String, Vec<Segment>>;

/// Emit the full `Prompt.swift` source for the given templates.
pub fn emit(templates: &Templates) -> Result<String> {
    // Resolve each template's parameter list (own variables plus those pulled in
    // transitively through includes). This also validates that include targets
    // exist and that there are no cycles.
    let mut params: BTreeMap<String, Vec<String>> = BTreeMap::new();
    for rel in templates.keys() {
        let mut stack = Vec::new();
        resolve_params(rel, templates, &mut params, &mut stack)?;
    }

    let mut tree = Node::default();
    for rel in templates.keys() {
        tree.insert(rel);
    }

    let mut out = String::from(HEADER);
    out.push_str("import Foundation\n\n");
    out.push_str(
        "/// Agent prompts generated from design/prompts/. Edit the `.jinja` files, not this file.\n",
    );
    out.push_str("enum Prompt {\n");
    write_body(&tree, templates, &params, &mut out, 1)?;
    out.push_str("}\n");
    Ok(out)
}

// MARK: - Parameter resolution

fn resolve_params(
    rel: &str,
    templates: &Templates,
    cache: &mut BTreeMap<String, Vec<String>>,
    stack: &mut Vec<String>,
) -> Result<Vec<String>> {
    if let Some(params) = cache.get(rel) {
        return Ok(params.clone());
    }
    if stack.iter().any(|s| s == rel) {
        stack.push(rel.to_string());
        bail!("include cycle detected: {}", stack.join(" -> "));
    }
    let segments = templates
        .get(rel)
        .ok_or_else(|| anyhow!("included template `{rel}` does not exist"))?;

    stack.push(rel.to_string());
    let mut params = Vec::new();
    collect_params(segments, templates, cache, stack, &mut params)?;
    stack.pop();

    cache.insert(rel.to_string(), params.clone());
    Ok(params)
}

fn collect_params(
    segments: &[Segment],
    templates: &Templates,
    cache: &mut BTreeMap<String, Vec<String>>,
    stack: &mut Vec<String>,
    params: &mut Vec<String>,
) -> Result<()> {
    for segment in segments {
        match segment {
            Segment::Text(_) => {}
            Segment::Var(v) => push_unique(params, v),
            Segment::Include(path) => {
                for p in resolve_params(path, templates, cache, stack)? {
                    push_unique(params, &p);
                }
            }
            Segment::If { cond, then, els } => {
                push_unique(params, cond);
                collect_params(then, templates, cache, stack, params)?;
                collect_params(els, templates, cache, stack, params)?;
            }
        }
    }
    Ok(())
}

fn push_unique(params: &mut Vec<String>, value: &str) {
    if !params.iter().any(|p| p == value) {
        params.push(value.to_string());
    }
}

// MARK: - Folder tree

#[derive(Default)]
struct Node {
    folders: BTreeMap<String, Node>,
    files: Vec<String>,
}

impl Node {
    fn insert(&mut self, rel: &str) {
        let components: Vec<&str> = rel.split('/').collect();
        let mut node = self;
        for folder in &components[..components.len() - 1] {
            node = node.folders.entry((*folder).to_string()).or_default();
        }
        node.files.push(rel.to_string());
    }
}

fn write_body(
    node: &Node,
    templates: &Templates,
    params: &BTreeMap<String, Vec<String>>,
    out: &mut String,
    depth: usize,
) -> Result<()> {
    let indent = "    ".repeat(depth);

    for (folder, sub) in &node.folders {
        writeln!(out, "{indent}enum {} {{", pascal_case(folder)).unwrap();
        write_body(sub, templates, params, out, depth + 1)?;
        writeln!(out, "{indent}}}").unwrap();
    }

    let mut files = node.files.clone();
    files.sort();
    for rel in &files {
        emit_leaf(rel, templates, params, out, depth)?;
    }

    Ok(())
}

// MARK: - Leaf emission

fn emit_leaf(
    rel: &str,
    templates: &Templates,
    params: &BTreeMap<String, Vec<String>>,
    out: &mut String,
    depth: usize,
) -> Result<()> {
    let indent = "    ".repeat(depth);
    let name = leaf_name(rel);
    let segments = &templates[rel];
    let leaf_params = &params[rel];

    if leaf_params.is_empty() {
        writeln!(
            out,
            "{indent}static let {name} = {}",
            literal(segments, params, depth + 1)
        )
        .unwrap();
        return Ok(());
    }

    let signature = leaf_params
        .iter()
        .map(|p| format!("{}: String", swift_ident_escape(p)))
        .collect::<Vec<_>>()
        .join(", ");
    writeln!(out, "{indent}static func {name}({signature}) -> String {{").unwrap();

    let body_indent = "    ".repeat(depth + 1);
    if has_if(segments) {
        writeln!(out, "{body_indent}var out = \"\"").unwrap();
        emit_imperative(segments, params, out, depth + 1);
        writeln!(out, "{body_indent}return out").unwrap();
    } else {
        writeln!(out, "{body_indent}{}", literal(segments, params, depth + 2)).unwrap();
    }
    writeln!(out, "{indent}}}").unwrap();
    Ok(())
}

/// Render if-free segments as a single Swift string-literal expression. Long
/// multi-line prose is emitted as a `"""` literal (so the prompt reads naturally
/// in the generated file); short fragments stay single-line. `content_indent` is
/// the indentation level used for a multi-line literal's body and closing `"""`.
fn literal(
    segments: &[Segment],
    params: &BTreeMap<String, Vec<String>>,
    content_indent: usize,
) -> String {
    let text_len: usize = segments
        .iter()
        .filter_map(|s| match s {
            Segment::Text(t) => Some(t.chars().count()),
            _ => None,
        })
        .sum();
    let newlines: usize = segments
        .iter()
        .filter_map(|s| match s {
            Segment::Text(t) => Some(t.matches('\n').count()),
            _ => None,
        })
        .sum();
    let has_cr = segments
        .iter()
        .any(|s| matches!(s, Segment::Text(t) if t.contains('\r')));

    if newlines >= 2 && text_len >= 40 && !has_cr {
        multiline_literal(&render_inner(segments, params, true), content_indent)
    } else {
        format!("\"{}\"", render_inner(segments, params, false))
    }
}

/// Concatenate segments into the inner body of a Swift string literal, with
/// variables and includes rendered as `\(...)` interpolations.
fn render_inner(
    segments: &[Segment],
    params: &BTreeMap<String, Vec<String>>,
    multiline: bool,
) -> String {
    let mut out = String::new();
    for segment in segments {
        match segment {
            Segment::Text(t) => out.push_str(&if multiline {
                escape_multiline(t)
            } else {
                escape_single(t)
            }),
            Segment::Var(v) => {
                out.push_str("\\(");
                out.push_str(&swift_ident_escape(v));
                out.push(')');
            }
            Segment::Include(path) => {
                out.push_str("\\(");
                out.push_str(&include_call(path, params));
                out.push(')');
            }
            Segment::If { .. } => unreachable!("literal called with an if segment"),
        }
    }
    out
}

/// Wrap an already-escaped inner body (which may contain real newlines and
/// `\(...)` interpolations) as a Swift `"""` literal. Each non-blank line is
/// indented to `content_indent`, matching the closing delimiter so Swift strips
/// exactly that indentation back off — keeping the value byte-identical.
fn multiline_literal(inner: &str, content_indent: usize) -> String {
    let pad = "    ".repeat(content_indent);
    let mut out = String::from("\"\"\"\n");
    for line in inner.split('\n') {
        if line.is_empty() {
            out.push('\n');
        } else {
            out.push_str(&pad);
            out.push_str(line);
            out.push('\n');
        }
    }
    out.push_str(&pad);
    out.push_str("\"\"\"");
    out
}

fn emit_imperative(
    segments: &[Segment],
    params: &BTreeMap<String, Vec<String>>,
    out: &mut String,
    depth: usize,
) {
    let indent = "    ".repeat(depth);
    let mut run: Vec<Segment> = Vec::new();

    for segment in segments {
        match segment {
            Segment::If { cond, then, els } => {
                flush_run(&mut run, params, out, depth);
                writeln!(out, "{indent}if !{}.isEmpty {{", swift_ident_escape(cond)).unwrap();
                emit_imperative(then, params, out, depth + 1);
                if els.is_empty() {
                    writeln!(out, "{indent}}}").unwrap();
                } else {
                    writeln!(out, "{indent}}} else {{").unwrap();
                    emit_imperative(els, params, out, depth + 1);
                    writeln!(out, "{indent}}}").unwrap();
                }
            }
            other => run.push(other.clone()),
        }
    }
    flush_run(&mut run, params, out, depth);
}

/// Append a run of consecutive non-`if` segments as a single `out += ...`.
fn flush_run(
    run: &mut Vec<Segment>,
    params: &BTreeMap<String, Vec<String>>,
    out: &mut String,
    depth: usize,
) {
    if run.is_empty() {
        return;
    }
    let indent = "    ".repeat(depth);
    writeln!(out, "{indent}out += {}", literal(run, params, depth + 1)).unwrap();
    run.clear();
}

/// A call/reference to the generated symbol for an included template, forwarding
/// its parameters by name.
fn include_call(path: &str, params: &BTreeMap<String, Vec<String>>) -> String {
    let symbol = symbol(path);
    let sub = params.get(path).cloned().unwrap_or_default();
    if sub.is_empty() {
        symbol
    } else {
        let args = sub
            .iter()
            .map(|p| format!("{0}: {0}", swift_ident_escape(p)))
            .collect::<Vec<_>>()
            .join(", ");
        format!("{symbol}({args})")
    }
}

fn has_if(segments: &[Segment]) -> bool {
    segments.iter().any(|s| matches!(s, Segment::If { .. }))
}

/// Escapes a string's contents for embedding inside a single-line Swift `"..."`.
fn escape_single(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for c in s.chars() {
        match c {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            '\0' => out.push_str("\\0"),
            _ => out.push(c),
        }
    }
    out
}

/// Escapes a string's contents for embedding inside a Swift `"""..."""` literal.
///
/// Newlines and `"` stay literal (that's the readability win); only backslashes
/// and any `"""` run that would otherwise close the literal are escaped.
fn escape_multiline(s: &str) -> String {
    s.replace('\\', "\\\\").replace("\"\"\"", "\"\"\\\"")
}

/// `"background/intent_item.jinja"` → `"Prompt.Background.intentItem"`.
fn symbol(rel: &str) -> String {
    let stem = rel.strip_suffix(".jinja").unwrap_or(rel);
    let components: Vec<&str> = stem.split('/').collect();
    let (file, folders) = components.split_last().expect("non-empty path");

    let mut symbol = String::from("Prompt");
    for folder in folders {
        symbol.push('.');
        symbol.push_str(&pascal_case(folder));
    }
    symbol.push('.');
    symbol.push_str(&leaf_ident(file));
    symbol
}

fn leaf_name(rel: &str) -> String {
    let stem = rel.strip_suffix(".jinja").unwrap_or(rel);
    let file = stem.rsplit('/').next().unwrap();
    leaf_ident(file)
}

fn leaf_ident(file: &str) -> String {
    swift_ident_escape(&camel_case(file))
}

#[cfg(test)]
mod tests {
    use super::super::parser::parse;
    use super::*;

    fn templates(entries: &[(&str, &str)]) -> Templates {
        entries
            .iter()
            .map(|(rel, src)| (rel.to_string(), parse(src).unwrap()))
            .collect()
    }

    #[test]
    fn static_template_is_constant() {
        let swift = emit(&templates(&[("system/small.jinja", "You are a local AI.")])).unwrap();
        assert!(swift.contains("enum System {"));
        assert!(swift.contains("static let small = \"You are a local AI.\""));
    }

    #[test]
    fn variables_become_string_params() {
        let swift = emit(&templates(&[(
            "onboarding/chat.jinja",
            "Hi {{ name }} in {{ language }}",
        )]))
        .unwrap();
        assert!(swift.contains("static func chat(name: String, language: String) -> String {"));
        assert!(swift.contains("\"Hi \\(name) in \\(language)\""));
    }

    #[test]
    fn if_block_emits_swift_guard() {
        let swift = emit(&templates(&[(
            "system/preamble.jinja",
            "You{% if about %}\n\n{{ about }}{% endif %}",
        )]))
        .unwrap();
        assert!(swift.contains("static func preamble(about: String) -> String {"));
        assert!(swift.contains("if !about.isEmpty {"));
        assert!(swift.contains("out += \"\\n\\n\\(about)\""));
    }

    #[test]
    fn long_prose_uses_triple_quote_literal() {
        let prose = "Line one of the prompt goes here.\n\nLine two adds more detail.\n\nLine three wraps it up nicely.";
        let swift = emit(&templates(&[("system/body.jinja", prose)])).unwrap();
        assert!(swift.contains("static let body = \"\"\"\n"));
        assert!(swift.contains("Line one of the prompt goes here."));
        assert!(swift.contains("\"\"\""));
        // No escaped newlines in the multi-line form.
        assert!(!swift.contains("\\n"));
    }

    #[test]
    fn include_of_static_partial_is_referenced() {
        let swift = emit(&templates(&[
            ("system/behavioral.jinja", "Be kind."),
            (
                "system/body.jinja",
                "Body.\n{% include \"system/behavioral.jinja\" %}",
            ),
        ]))
        .unwrap();
        // body has no own vars and its include is param-less → still a constant.
        assert!(swift.contains("static let body = \"Body.\\n\\(Prompt.System.behavioral)\""));
        assert!(swift.contains("static let behavioral = \"Be kind.\""));
    }

    #[test]
    fn include_forwards_parametric_params() {
        let swift = emit(&templates(&[
            ("a/item.jinja", "- {{ label }}"),
            ("a/frame.jinja", "List:\n{% include \"a/item.jinja\" %}"),
        ]))
        .unwrap();
        assert!(swift.contains("static func frame(label: String) -> String {"));
        assert!(swift.contains("\\(Prompt.A.item(label: label))"));
    }

    #[test]
    fn missing_include_target_errors() {
        let err = emit(&templates(&[(
            "a/frame.jinja",
            "{% include \"a/missing.jinja\" %}",
        )]))
        .unwrap_err();
        assert!(err.to_string().contains("does not exist"));
    }

    #[test]
    fn include_cycle_errors() {
        let err = emit(&templates(&[
            ("a.jinja", "{% include \"b.jinja\" %}"),
            ("b.jinja", "{% include \"a.jinja\" %}"),
        ]))
        .unwrap_err();
        assert!(err.to_string().contains("cycle"));
    }

    #[test]
    fn escapes_quotes_and_backslashes() {
        let swift = emit(&templates(&[("x/q.jinja", "say \"hi\" and \\ here")])).unwrap();
        assert!(swift.contains(r#"static let q = "say \"hi\" and \\ here""#));
    }

    #[test]
    fn dedupes_repeated_variables() {
        let swift = emit(&templates(&[("x/y.jinja", "{{ a }}{{ a }}{{ b }}")])).unwrap();
        assert!(swift.contains("static func y(a: String, b: String) -> String {"));
    }
}
