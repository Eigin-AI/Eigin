use super::{parser, swift as generator};
use anyhow::{Context, Result, bail};
use std::collections::BTreeMap;
use std::fs;
use std::path::Path;

const RESOURCE: &str = "src/eigin_sdk/crates/eigin_sdk/resources/prompts.json";
const SWIFT_API: &str = "src/eigin_sdk/apple/EiginSDK/Sources/EiginSDK/DefaultPrompts.swift";
const TESTS: &str = "src/eigin_sdk/apple/EiginSDK/Tests/EiginSDKTests";

pub struct Catalog {
    pub sources: BTreeMap<String, String>,
    pub templates: generator::Templates,
}

/// Load and validate prompt sources.
pub fn load(root: &Path) -> Result<Catalog> {
    let source = root.join("design/prompts");
    let mut sources = BTreeMap::new();
    collect(&source, &source, &mut sources)?;
    if sources.is_empty() {
        bail!("prompt source directory contains no templates");
    }
    let templates = sources
        .iter()
        .map(|(name, source)| {
            parser::parse(source)
                .with_context(|| format!("parsing {name}"))
                .map(|segments| (name.clone(), segments))
        })
        .collect::<Result<_>>()?;
    generator::emit(&templates)?;
    Ok(Catalog { sources, templates })
}

fn collect(root: &Path, dir: &Path, sources: &mut BTreeMap<String, String>) -> Result<()> {
    for entry in fs::read_dir(dir).with_context(|| format!("reading {}", dir.display()))? {
        let path = entry?.path();
        if path.is_dir() {
            collect(root, &path, sources)?;
        } else if path.extension().is_some_and(|ext| ext == "jinja") {
            let name = path
                .strip_prefix(root)?
                .to_str()
                .context("non-UTF8 prompt path")?
                .replace('\\', "/");
            sources.insert(name, fs::read_to_string(&path)?);
        }
    }
    Ok(())
}

/// Generate SDK resources and exhaustive Swift binding probes without Swift tools.
pub fn generate(root: &str, check: bool) -> Result<()> {
    let root = Path::new(root);
    let catalog = load(root)?;
    let document = serde_json::json!({"schema_version": 1, "templates": catalog.sources});
    let json = format!("{}\n", serde_json::to_string_pretty(&document)?);
    output(&root.join(RESOURCE), &json, check)?;
    let facade = generator::emit(&catalog.templates)?;
    output(&root.join(SWIFT_API), &facade, check)?;
    let parameters = generator::resolve_all_params(&catalog.templates)?;
    output(
        &root.join("src/eigin_sdk/web/tests/default-prompt-parameters.ts"),
        &format!(
            "// Generated by eigin-tools — do not edit.\n// prettier-ignore\nexport const defaultPromptParameters = {};\n",
            serde_json::to_string_pretty(&parameters)?
        ),
        check,
    )?;
    output(
        &root.join(TESTS).join("GeneratedPromptTests.swift"),
        &probes(&catalog)?,
        check,
    )?;
    Ok(())
}

fn output(path: &Path, content: &str, check: bool) -> Result<()> {
    if fs::read_to_string(path).ok().as_deref() == Some(content) {
        return Ok(());
    }
    if check {
        bail!(
            "stale generated prompt output: {} (run just generate sdk)",
            path.display()
        );
    }
    fs::create_dir_all(path.parent().unwrap())?;
    fs::write(path, content)?;
    Ok(())
}

fn probes(catalog: &Catalog) -> Result<String> {
    let params = generator::resolve_all_params(&catalog.templates)?;
    let mut out = String::from(
        "// Generated by eigin-tools — do not edit.\n// swiftformat:disable all\nimport EiginSDK\nimport Testing\n\n@Test func allBundledPromptAccessors() throws {\n    let catalog = EiginSDK.PromptCatalog.defaultCatalog()\n",
    );
    for (name, parameters) in &params {
        let symbol = generator::sdk_symbol(name);
        for empty in [true, false] {
            let sample = |parameter: &str| {
                generator::quote(&if empty {
                    String::new()
                } else {
                    format!("Sample {parameter}")
                })
            };
            let args = parameters
                .iter()
                .map(|p| {
                    format!(
                        "{}: {}",
                        crate::codegen::ios::swift_ident_escape(p),
                        sample(p)
                    )
                })
                .collect::<Vec<_>>()
                .join(", ");
            let call = if parameters.is_empty() {
                symbol.clone()
            } else {
                format!("{symbol}({args})")
            };
            let dict = parameters
                .iter()
                .map(|p| format!("{}: {}", generator::quote(p), sample(p)))
                .collect::<Vec<_>>()
                .join(", ");
            let dict = if parameters.is_empty() {
                ":".into()
            } else {
                dict
            };
            out.push_str(&format!(
                "    #expect({call} == (try catalog.render(name: {}, parameters: [{dict}])))\n",
                generator::quote(name)
            ));
        }
    }
    out.push_str("}\n");
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn generation_is_deterministic_and_checks_stale_outputs() {
        let dir = tempfile::tempdir().unwrap();
        let root = dir.path();
        fs::create_dir_all(root.join("design/prompts")).unwrap();
        fs::write(root.join("design/prompts/a.jinja"), "Hello {{ name }}").unwrap();
        generate(root.to_str().unwrap(), false).unwrap();
        generate(root.to_str().unwrap(), true).unwrap();
        let before = fs::read(root.join(RESOURCE)).unwrap();
        generate(root.to_str().unwrap(), false).unwrap();
        assert_eq!(before, fs::read(root.join(RESOURCE)).unwrap());
        fs::write(root.join("design/prompts/a.jinja"), "Changed").unwrap();
        assert!(generate(root.to_str().unwrap(), true).is_err());
    }

    #[test]
    fn missing_empty_and_invalid_sources_fail() {
        let dir = tempfile::tempdir().unwrap();
        assert!(load(dir.path()).is_err());
        fs::create_dir_all(dir.path().join("design/prompts")).unwrap();
        assert!(load(dir.path()).is_err());
        fs::write(
            dir.path().join("design/prompts/a.jinja"),
            "{% include 'missing' %}",
        )
        .unwrap();
        assert!(load(dir.path()).is_err());
    }
}
